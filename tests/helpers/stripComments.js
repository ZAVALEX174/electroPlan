/* Общий хелпер структурных *Wiring-тестов: вырезание комментариев из исходника перед
   сопоставлением регэкспами.

   ЗАЧЕМ ОДИН НА ВСЕХ. В проекте есть известная дыра: регэксп вида /renderProperties\s*\(/ матчит
   вызов, ЗАКОММЕНТИРОВАННЫЙ рядом, и мутация «закомментировать вызов, не удаляя строку» оставляет
   структурный тест зелёным. Раньше вырезание комментариев было скопировано в отдельные файлы —
   тот же дефект «правило размножено», за который чинили app.js. Держим правило в ОДНОМ месте.

   ЧТО ДЕЛАЕТ. Снимает блочные и строчные комментарии. Строчные (две косые черты) — только когда
   перед ними стоит символ, отличный от двоеточия (чтобы не порвать "://" в URL). Токены, по
   которым сверяются Wiring-тесты (имена функций проекта), в строковых литералах и регэкспах
   app.js не встречаются, поэтому грубого стрипа достаточно — он может лишь убрать лишнее, но не
   подставить ложное совпадение по искомым именам. */
function stripComments(s) {
  return s
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/([^:])\/\/[^\n]*/g, "$1");
}

module.exports = { stripComments: stripComments };
