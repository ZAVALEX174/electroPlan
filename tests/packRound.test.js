/* Правило «кратно упаковке» (К6, решение владельца 22.10): количество заказа округляется ВВЕРХ до
   целых упаковок поставщика. Единственная копия правила — js/packRound.js (EPPackRound.packRound),
   её зовёт лист «По артикулам» (К6а), следом КП и панель итогов (К6б). Поэтому правило проверяем
   прямой функцией — здесь, а его применение в книге — в tests/packMultipleExcel.test.js.

   Это ДЕНЬГИ (количество × цена = сумма заказа), поэтому к каждому утверждению — мутация.
   МУТАЦИОННАЯ ТАБЛИЦА (прогнано лично, см. отчёт):
     · убрать Math.ceil (вернуть q/p*p) → краснеет «7/10 → 10» (даёт 7);
     · вернуть q вместо Math.ceil(q/p)*p → краснеет «7/10 → 10» и «11/10 → 20»;
     · снять гейт `p<=0 → q` (округлять всегда) → краснеет «упаковка 0 → как есть» (деление на 0 даёт NaN/Infinity);
     · снять гейт `q<=0 → q` (возвращать Math.ceil и для нуля) → «0 → 0» остаётся зелёным (0 кратно),
       но «-3 → как есть» краснеет (Math.ceil(-0.3)*10 = 0, а не -3).
   Запуск: node --test tests/packRound.test.js */
"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { packRound } = require("../js/packRound.js");

test("packRound: вверх до целых упаковок, когда упаковка известна", () => {
  assert.equal(packRound(7, 10), 10, "нужно 7, упаковка 10 → 10 (одна целая упаковка)");
  assert.equal(packRound(10, 10), 10, "ровно упаковка → она же, лишнего не добираем");
  assert.equal(packRound(11, 10), 20, "11 → две упаковки (20)");
  assert.equal(packRound(1, 10), 10, "одна штука → всё равно целая упаковка");
  assert.equal(packRound(25, 5), 25, "кратное упаковке остаётся собой");
  assert.equal(packRound(26, 5), 30, "26 при упаковке 5 → 30");
});

test("packRound: упаковка неизвестна/невалидна → количество НЕ трогаем", () => {
  /* «Упаковки не знаем» ≠ «упаковка = 1»: в первом случае округлять не на что, число отдаём как есть
     (граница К6а: нет данных об упаковке → без округления). */
  assert.equal(packRound(7, null), 7, "null упаковки → как есть");
  assert.equal(packRound(7, undefined), 7, "undefined → как есть");
  assert.equal(packRound(7, 0), 7, "упаковка 0 (деление на 0 запрещено) → как есть");
  assert.equal(packRound(7, -10), 7, "отрицательная упаковка → как есть");
  assert.equal(packRound(7, NaN), 7, "мусор в упаковке → как есть");
});

test("packRound: нулевое/отрицательное количество → как есть (нечего укладывать)", () => {
  assert.equal(packRound(0, 10), 0, "0 заказать → 0 упаковок");
  assert.equal(packRound(-3, 10), -3, "отрицательное количество не превращаем в 0");
});

test("packRound: мусор в количестве отдаём как есть, а не как число", () => {
  assert.equal(packRound(undefined, 10), undefined, "undefined количества не превращаем в 0 молча");
  assert.equal(packRound("x", 10), "x", "нечисловое количество возвращаем как пришло");
});
