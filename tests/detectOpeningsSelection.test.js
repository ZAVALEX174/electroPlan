/* ОТБОР ПЯТЕН-ОКОН по площади (tools/detect-openings.mjs → keepComponents), задача НАКЛАДКА-ФОТО.

   ЧТО ЧИНИЛИ. Прежний единый порог minpix = 0.004·площадь резал реальные УЗКИЕ ОВАЛЫ винтажных
   накладок наравне с точечным шумом. На кадре 22674 (200×129, площадь 25800 → порог 103) детектор
   находил четыре одинаковых овала n=106/96/96/93 и точку-шум n=1, а порог 103 оставлял только
   ПЕРВЫЙ овал (106) и выкидывал три (96/96/93) — разница между 106 и 96 это JPEG-шум, а не смысл.
   Итог: «4 модуля на 4 выключателя» получали одно окно и пост схлопывался.

   ПОЧИНКА. Порог = max(абсолютный пол ABS_FLOOR·площадь, доля REL_FLOOR от самого крупного пятна).
   Относительное правило держит равные окна вместе (не делит их произвольно), абсолютное страхует
   вырожденный кадр без окон. Фикстуры — реальные компоненты из разведки владельца.

   Запуск: node --test tests/ */
"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");

async function loadKeep() {
  const mod = await import("../tools/detect-openings.mjs");
  return mod.keepComponents;
}

test("22674: четыре равных овала остаются вместе, точечный шум отсекается", async () => {
  const keepComponents = await loadKeep();
  // Реальные компоненты кадра 22674.jpg (200×129) из разведки: 4 овала + одна точка-шум.
  const comps = [
    { n: 106, rect: [25.5, 44.2, 4.5, 10.9] },
    { n: 96, rect: [40.5, 43.4, 4.5, 11.6] },
    { n: 96, rect: [70, 44.2, 4.5, 10.9] },
    { n: 93, rect: [55, 44.2, 4.5, 10.9] },
    { n: 1, rect: [44.5, 46.5, 0.5, 0.8] },
  ];
  const kept = keepComponents(comps, 200, 129);
  assert.equal(kept.length, 4, "все четыре равных овала обязаны пройти (не делим равные окна)");
  assert.ok(!kept.some(r => r[2] === 0.5 && r[3] === 0.8), "точечный шум n=1 не должен пройти");
  // Контроль ПРИЧИНЫ: старый порог 0.004·площадь оставил бы только n≥103, то есть один овал.
  const oldMin = 0.004 * 200 * 129;
  assert.equal(comps.filter(c => c.n >= oldMin).length, 1, "разведочный контроль: старый порог оставлял ровно 1 окно");
});

test("вырожденный кадр 21653: только блики (max n=43) — ни одного окна", async () => {
  const keepComponents = await loadKeep();
  // Компоненты 21653.jpg (200×171, цельная пластина Eikon Evo без сквозного окна): всё это блики.
  const comps = [
    { n: 43, rect: [42.5, 8.2, 21.5, 0.6] },
    { n: 26, rect: [56, 67.3, 13, 0.6] },
    { n: 25, rect: [25.5, 38.6, 0.5, 14.6] },
    { n: 24, rect: [35.5, 67.3, 12, 0.6] },
    { n: 17, rect: [32, 28.1, 8.5, 0.6] },
    { n: 8, rect: [68, 8.2, 4, 0.6] },
  ];
  const kept = keepComponents(comps, 200, 171);
  assert.equal(kept.length, 0, "абсолютный пол (0.002·34200=68) обязан отсечь блик-максимум n=43");
});

test("одно крупное окно проходит, мелкие блики рядом с ним — нет (относительный порог)", async () => {
  const keepComponents = await loadKeep();
  // Один настоящий проём и несколько бликов по канту (как на 14657.AB: n=6556 + 178/72/71).
  const comps = [
    { n: 6556, rect: [12, 19, 75.5, 57] },
    { n: 178, rect: [5, 5, 6, 1] },
    { n: 72, rect: [90, 90, 3, 1] },
    { n: 71, rect: [50, 95, 3, 1] },
  ];
  const kept = keepComponents(comps, 200, 79);
  assert.equal(kept.length, 1, "относительный порог 0.25·6556=1639 оставляет только настоящий проём");
  assert.deepEqual(kept[0], [12, 19, 75.5, 57]);
});

test("порог удерживает самый мелкий реальный овал каталога (n=93) выше абсолютного пола", async () => {
  const keepComponents = await loadKeep();
  // Граничный контроль: одиночный овал n=93 на площади 25800 (0.002·25800=52) обязан пройти.
  assert.equal(keepComponents([{ n: 93, rect: [55, 44.2, 4.5, 10.9] }], 200, 129).length, 1);
});
