/* ПОВЕДЕНЧЕСКИЙ регресс правила «в какой комнате точка» (resolveRoomForPoint из js/app.js).

   ЗАЧЕМ ЭТОТ ТЕСТ, ЕСЛИ ЕСТЬ roomAssignSingleRuleWiring.test.js. Тот проверяет ТЕКСТ app.js
   (правило существует в одном экземпляре, допуск берётся из EPConfig) — но не исполняет его. Из-за
   этого зелёными оставались три дефекта ревью:
     - resolveRoomForPoint падал с ReferenceError: distancePointToSegment не был проброшен в app.js
       (свободное имя в строгом IIFE) — связка вообще не исполнялась, а ни один тест этого не видел;
     - величину допуска можно было раздуть с 12 до 120 (объекты липнут через полквартиры);
     - ветвь допуска можно было переставить перед проверкой попадания (реальное попадание в контур
       переопределялось), а grid-ветвь — оставить раньше допуска (ручная подпись комнаты перехватывала
       объект на контуре другой, полигональной комнаты).

   ИДЕЯ. app.js — монолит-оркестратор (DOM, state), в node не грузится. Но resolveRoomForPoint —
   чистая функция: все зависимости приходят через ctx и через геометрию/конфиг. Мы вырезаем её ИСХОДНЫЙ
   ТЕКСТ из app.js и исполняем в изолированном контексте vm, куда кладём РОВНО те геометрические имена,
   которые app.js сам пробрасывает строкой `const {...}=EPGeom;`. Тогда:
     - если в этой строке снова забудут нужный алиас (как было с distancePointToSegment), функция
       упадёт с ReferenceError ровно так же, как в браузере, — и тест это поймает (класс «связка не
       исполняется»);
     - порядок ветвей и величина допуска проверяются НАСТОЯЩИМ прогоном на координатах, а не по тексту.

   Мы НЕ переписываем правило в тесте — исполняем именно то, что лежит в app.js. Второй копии логики
   не заводим (это и стережёт roomAssignSingleRuleWiring.test.js). Запуск: node --test tests/ */
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const EPGeom = require("../js/geometry.js");
const EPRoomAssign = require("../js/roomAssign.js");
const EPConfig = require("../js/config.js");

const SRC = fs.readFileSync(path.join(__dirname, "..", "js", "app.js"), "utf8");

/* Имена, которые app.js достаёт из EPGeom деструктуризацией верхнего уровня. Собираем контекст
   ТОЛЬКО из них — иначе тест «прощал» бы забытый алиас и не воспроизводил браузерный ReferenceError. */
function aliasedGeomNames() {
  const m = SRC.match(/const\s*\{([^}]*)\}\s*=\s*EPGeom\s*;/);
  assert.ok(m, "в app.js не нашлась строка алиасов `const {...}=EPGeom;`");
  return m[1].split(",").map(s => s.trim()).filter(Boolean);
}

/* Вырезаем исходник функции: от её объявления до следующего `\nfunction ` верхнего уровня
   (соседей у неё — getRoomForPoint), между ними только `}` и пустая строка — валидный JS. */
function functionSource(name) {
  const start = SRC.indexOf("function " + name);
  assert.ok(start >= 0, "функция " + name + " должна существовать в app.js");
  const rest = SRC.slice(start);
  const nextIdx = rest.indexOf("\nfunction ", 1);
  return nextIdx >= 0 ? rest.slice(0, nextIdx) : rest;
}

/* Живая resolveRoomForPoint в песочнице с окружением, повторяющим лексику app.js:
   - геометрические имена — только те, что реально проброшены (aliasedGeomNames);
   - namespace EPGeom целиком (если правило зовёт EPGeom.distancePointToSegment вместо алиаса);
   - EPRoomAssign / EPConfig — глобалы, как в браузере. */
function buildResolver() {
  const ctx = { EPGeom, EPRoomAssign, EPConfig };
  for (const name of aliasedGeomNames()) ctx[name] = EPGeom[name];
  vm.createContext(ctx);
  return vm.runInContext(functionSource("resolveRoomForPoint") + "\n;resolveRoomForPoint;", ctx);
}

/* Прямоугольный контур комнаты в форме state.rooms.{polygon:[{x,y}]}. */
const rect = (x1, y1, x2, y2) => [
  { x: x1, y: y1 }, { x: x2, y: y1 }, { x: x2, y: y2 }, { x: x1, y: y2 }
];
/* Карта пространства, где ВСЯ плоскость — одна компонента связности id=comp: одна клетка на весь
   план, не заблокирована. Так grid-«подпись» имитирует реальную ситуацию — компонента через
   проёмы накрывает всю квартиру. componentAt(map,*,*) вернёт comp для любой точки. */
const wholePlaneMap = comp => ({ cols: 1, rows: 1, cell: 1e6, originX: 0, originY: 0, blocked: [false], component: [comp] });

const resolve = buildResolver();

/* --- Класс «связка не исполняется» (дефект 1) -----------------------------------------------
   Прогон, гарантированно уходящий в ветвь допуска (точка вне всех контуров, но у границы), обязан
   отработать без исключения. Если distancePointToSegment снова выпадет из алиасов app.js — здесь
   выстрелит ReferenceError, ровно как в браузере, и тест покраснеет. */
test("resolveRoomForPoint исполняется целиком: ветвь допуска не роняет ReferenceError", () => {
  const ctx = { polyRooms: [{ id: "A", polygon: rect(0, 0, 100, 100) }], gridRooms: [], map: null };
  assert.doesNotThrow(() => resolve(50, -6, ctx),
    "ветвь допуска должна отработать — все свободные имена resolveRoomForPoint обязаны быть доступны в app.js");
  const r = resolve(50, -6, ctx);   // (50,-6): в 6 px над верхним ребром → внутри допуска
  assert.ok(r && r.id === "A", "точка у границы контура обязана привязаться к комнате через допуск");
});

/* --- Порядок: настоящее попадание в контур НЕ переопределяется допуском (дефект 3, мутация «допуск
   перед попаданием») ---------------------------------------------------------------------------
   Спальня и Кухня — смежные контуры с общей стеной x=100. Точка (99,50) лежит ВНУТРИ Спальни, но до
   её правой стены и до левой стены Кухни расстояние равное (1 px). При верном порядке pointInPolygon
   отдаёт Спальню сразу. Если допуск переставить перед попаданием, он на равном расстоянии выберет по
   детерминированному тай-брейку меньший id — «Кухня» < «Спальня» — и вернёт НЕ ту комнату. */
test("попадание в контур сильнее допуска: точка внутри Спальни остаётся Спальней", () => {
  const ctx = {
    polyRooms: [
      { id: "Спальня", polygon: rect(0, 0, 100, 100) },
      { id: "Кухня", polygon: rect(100, 0, 200, 100) }
    ],
    gridRooms: [], map: null
  };
  const r = resolve(99, 50, ctx);
  assert.ok(r, "точка внутри контура обязана привязаться");
  assert.equal(r.id, "Спальня",
    "точка внутри Спальни не должна переопределяться допуском в пользу равноудалённой Кухни");
});

/* --- Порядок: допуск СИЛЬНЕЕ grid (дефект 2) --------------------------------------------------
   Контурная Спальня + ручная подпись «Кухня» (grid-комната без полигона, componentId накрывает всю
   плоскость). Пост центром РОВНО на правой стене Спальни (pointInPolygon → «снаружи»). Верный порядок:
   допуск находит Спальню. Старый порядок (grid раньше допуска): componentAt отдаёт компонент квартиры
   → Кухня. Тест краснеет, если grid снова окажется перед допуском. */
test("допуск сильнее grid: пост на контуре Спальни при подписи «Кухня» достаётся Спальне", () => {
  const ctx = {
    polyRooms: [{ id: "Спальня", polygon: rect(100, 100, 200, 300) }],
    gridRooms: [{ id: "Кухня", componentId: 7 }],
    map: wholePlaneMap(7)
  };
  // центр объекта на правой стене Спальни: x=200 (на линии), y=212 (внутри диапазона стены)
  const r = resolve(200, 212, ctx);
  assert.ok(r, "пост у стены обязан к чему-то привязаться");
  assert.equal(r.id, "Спальня", "объект на контуре Спальни не должна перехватывать подпись-Кухня");
});

/* --- Инвариант: grid работает как раньше в проектах без контуров -------------------------------
   polyRooms пуст → попадание и допуск не находят ничего → отрабатывает grid-ветвь. Перестановка
   ветвей не должна это ломать. */
test("grid-комнаты без контуров: перестановка ветвей их не задевает", () => {
  const ctx = { polyRooms: [], gridRooms: [{ id: "Гостиная", componentId: 7 }], map: wholePlaneMap(7) };
  const r = resolve(500, 500, ctx);
  assert.ok(r, "в проекте только с подписями объект обязан привязаться по grid");
  assert.equal(r.id, "Гостиная");
});

/* --- Величина допуска: пришпилена с двух сторон, без привязки к точному числу -------------------
   Один контур, grid нет. Точка в ~10 px от стены обязана привязаться (провалится, если допуск ужать
   вдвое, напр. 12→6). Точка в ~20 px обязана НЕ привязаться (провалится, если допуск раздуть вдвое,
   напр. 12→24, и тем более 12→120). Так изменение допуска «в разы» в любую сторону краснит тест, но
   он не ломается от косметической правки самого числа в разумных пределах. */
test("величина допуска: ~10 px привязывается, ~20 px — нет (ловит изменение в разы)", () => {
  const ctx = { polyRooms: [{ id: "A", polygon: rect(0, 0, 100, 100) }], gridRooms: [], map: null };
  // (50,-10): 10 px над верхним ребром — внутри допуска 12
  const nearHit = resolve(50, -10, ctx);
  assert.ok(nearHit && nearHit.id === "A",
    "точка в ~10 px от контура обязана привязаться — иначе допуск урезали в разы");
  // (50,-20): 20 px над ребром — за пределами допуска 12
  const farMiss = resolve(50, -20, ctx);
  assert.equal(farMiss, null,
    "точка в ~20 px от контура НЕ должна привязываться — иначе допуск раздули в разы");
});
