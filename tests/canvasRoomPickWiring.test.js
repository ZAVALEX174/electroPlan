/* Структурный регресс-тест: КЛИК выбора/удаления комнаты на холсте идёт через единое правило
   «точка → теснейшая накрывающая» (EPGeom.tightestRoomAtPoint), а не через перебор state.rooms по
   порядку массива (В20 п.2).

   ЗАЧЕМ ТЕСТ ПО ТЕКСТУ. Обработчик canvas.onclick — анонимная стрелка ВНУТРИ EPCanvasInput.attach(ctx):
   он держит замыкание на state/DOM/ctx и в node живьём не исполняется (как и makeDraggable — там же
   отказались от поведенческого теста, В19). Поведенческий дефект был денежно-данных: правило «точка →
   комната» жило в ДВУХ копиях — фактическая привязка брала теснейшую комнату (пост в чулане считался по
   чулану), а клик — ПЕРВУЮ в state.rooms (ручные идут первыми), поэтому «Удалить» внутри чулана удаляло
   поправленный ЗАЛ вокруг (потеря данных), а под курсором подсвечивался чулан. Лечение по §7.1 — свести
   правило в ОДНУ чистую функцию tightestRoomAtPoint, которую зовёт и привязка, и клик. Этот тест стережёт
   инвариант проводки: оба места выбора комнаты кликом зовут общую функцию, а старого перебора по порядку
   в файле нет.

   ПОЧЕМУ ВЫРЕЗАЕМ КОММЕНТАРИИ. Известная дыра проекта: регэксп матчит имя в СОСЕДНЕМ комментарии (здесь
   tightestRoomAtPoint упомянут в пояснении у строки выбора), и мутация «закомментировать вызов» осталась
   бы зелёной. Поэтому сопоставляем по исходнику с вырезанными комментариями (общий stripComments) — для
   теста закомментированного вызова не существует.

   МУТАЦИОННАЯ ПРОВЕРКА (числа — в отчёте):
     · заменить `const room=tightestRoomAtPoint(x,y,state.rooms)` на `state.rooms.find(r=>r.polygon&&
       r.polygon.length>2)` в любом из двух мест → счётчик tightestRoomAtPoint( падает до 1 → красит
       «оба места кликом зовут tightestRoomAtPoint» (а появившийся state.rooms.find красит и второй тест);
     · вернуть прежний `state.rooms.find(r=>...pointInPolygon(x,y,r.polygon))` → красит «нет перебора
       по порядку с pointInPolygon» (и счётчик вызовов тоже падает).
   Запуск: node --test tests/ */
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { stripComments } = require("./helpers/stripComments.js");

const CANVAS = stripComments(fs.readFileSync(path.join(__dirname, "..", "js", "canvasInput.js"), "utf8"));

test("оба места выбора комнаты кликом зовут общую tightestRoomAtPoint (ровно два вызова)", () => {
  /* Два места: режим «Правка комнат» (клик по контуру показывает вершины) и выбор/«Удалить» кликом по
     пустому холсту. Оба обязаны брать комнату через tightestRoomAtPoint — то же правило, что привязка
     объектов (§7.1). Деструктуризация `tightestRoomAtPoint,` из ctx не считается (там запятая, не «(»).
     Падение счётчика до 1 — значит одно из мест вернулось к собственному перебору state.rooms. */
  const calls = (CANVAS.match(/tightestRoomAtPoint\s*\(/g) || []).length;
  assert.equal(calls, 2,
    "ожидалось ровно два вызова tightestRoomAtPoint( — по одному в каждом месте выбора комнаты кликом " +
    "(«Правка комнат» и выбор/«Удалить»); стало " + calls + ". Меньше — клик снова выбирает комнату сам, " +
    "мимо единого правила: под курсором подсветится одна комната, а выберется/удалится другая.");
});

test("в canvasInput.js нет выбора комнаты перебором state.rooms по порядку (ни с pointInPolygon, ни без)", () => {
  /* Прежний дефект — `state.rooms.find(r=>r.polygon&&r.polygon.length>2&&pointInPolygon(x,y,r.polygon))`:
     берёт ПЕРВУЮ по порядку массива накрывающую точку комнату. Любой `state.rooms.find(` в этом файле —
     возврат к перебору мимо tightestRoomAtPoint; стережём оба варианта мутации (с pointInPolygon и без). */
  assert.ok(!/state\.rooms\.find\s*\(/.test(CANVAS),
    "в canvasInput.js не должно быть state.rooms.find( — выбор комнаты кликом идёт только через " +
    "tightestRoomAtPoint; перебор по порядку массива возвращает денежно-данный дефект В20 п.2");
});
