/* Шаговый выбор отделки накладки (E14, вид «С картинками») — ЧИСТАЯ логика поверх уже готового
   отбора. Модуль без state, DOM и каталога: всё приходит аргументами, как в room.js/catalog.js
   (PLAN 7.1) — тогда шаги и счётчики забирают автотесты, а браузерная обёртка в app.js только
   рисует плитки.

   ★ ВТОРОЙ ВИД, А НЕ ВТОРОЕ ПРАВИЛО (§7.1). Мастер НЕ держит своей копии фильтра, своего списка
   значений и своего счётчика: и «сколько накладок за вариантом», и перечисление значений признака
   идут через ТЕ ЖЕ функции каталога, что уже фильтруют конструктор поста, — они приходят в deps:
     match(frames, criteria)  — EPCatalog.productsForRoom, ТОТ ЖЕ отбор, что у collectionFramePool и
                                у хинта конструктора (frameFacingHintText). Счётчик «за вариантом» —
                                это его .length, второго счётчика нет.
     valuesOf(pool, prop)     — перечисление значений признака В ПУЛЕ (EPCatalog.productCollections
                                для серии / productFacingValues для материала-формы-цвета). Список
                                значений мастер не хранит — берёт из каталога, суженного выбором.
     imageOf(item)            — URL фото товара (EPCatalog.productImage); «» когда фото нет.

   Порядок шагов — стандарт → серия → материал → форма → цвет. Монтажный стандарт стоит ПЕРВЫМ
   намеренно (встреча 24.08 §4.1: «первое, что должны мы выбрать» — конфигуратор сразу отсекает
   неподходящие рамки): выбор стандарта сужает и список серий на следующем шаге, и всё ниже.
   prop каждого шага — ТО ЖЕ имя поля комнаты, что пишет вид-список (standard/collection/
   frameMaterial/frameShape/frameColor): оба вида читают и пишут ОДНИ настройки комнаты, поэтому
   «что выбрано в одном виде, видно в другом» — по построению. */
(() => {
"use strict";

const STEPS = [
  { prop: "standard",      title: "Стандарт", label: "стандарт" },
  { prop: "collection",    title: "Серия",    label: "серия" },
  { prop: "frameMaterial", title: "Материал", label: "материал" },
  { prop: "frameShape",    title: "Форма",    label: "форма" },
  { prop: "frameColor",    title: "Цвет",     label: "цвет" }
];

/* Варианты одного шага: значения признака prop, каждый со счётчиком накладок за ним и картинкой
   товара-представителя. Считаем от ПУЛА, суженного ДРУГИМИ уже выбранными признаками (selection без
   prop): текущий признак как раз выбирают, поэтому он пул не сужает — иначе, вернувшись на шаг,
   человек видел бы счётчики только под текущее значение и не смог бы сравнить альтернативы.
   Значения берём из valuesOf(pool) — по построению это ровно те, что в пуле реально есть, поэтому у
   каждого варианта count > 0, а пустой список означает пустой пул (пустое сочетание — его объясняет
   словами вызывающий, конвенция E14). Картинку берём у ПЕРВОГО товара варианта, у которого фото
   есть: у ~40% накладок фото нет, но у варианта достаточно одного изделия с фото. */
function stepOptions(frames, selection, prop, deps) {
  const base = Object.assign({}, selection || {});
  delete base[prop];
  const pool = deps.match(frames, base);
  return deps.valuesOf(pool, prop).map(value => {
    const subset = deps.match(pool, { [prop]: value });
    const withImage = subset.find(item => deps.imageOf(item));
    return { value, count: subset.length, imageUrl: withImage ? deps.imageOf(withImage) : "" };
  });
}

/* Видимые шаги в ТЕКУЩЕМ отборе (К12 ч.1). Шаг показываем, только если у его признака в каталоге,
   суженном значениями ВЫШЕлежащих уже выбранных шагов, есть ≥2 значения: иначе выбирать не из чего,
   и шаг прячем. Так уходит «Форма» — у всех накладок VIMAR она одна («Классическая»), менять нечего
   (слова заказчика 15.10: «форму можно вообще убрать… чтобы не показывалась, если нет возможности
   поменять»). Появится бренд с двумя формами — значений станет ≥2 и шаг вернётся сам, без правки кода.
     Правило в ОДНОМ месте (§7.1): и окно подбора, и селекторы комнаты, и подсказка конструктора
   спрашивают видимость здесь — второго правила «когда прятать» нет.
     Сужаем ТОЛЬКО вышележащими выбранными шагами (каскад стандарт→серия→материал→форма→цвет): набор
   значений шага определяется выбором ДО него, а не после. Значение скрытого шага (например, форма из
   старого проекта) в сужение нижних шагов всё равно переносим — отбор остаётся прежним, сохранённое
   не стирается. Части 2 (автозаполнение единственного значения) и 3 (цвет механизмов) берут ту же
   функцию. */
function visibleSteps(frames, selection, deps) {
  const sel = selection || {};
  const above = {};
  const visible = [];
  STEPS.forEach(step => {
    const pool = deps.match(frames, above);
    const values = deps.valuesOf(pool, step.prop);
    const chosen = (typeof sel[step.prop] === "string" && sel[step.prop]) ? sel[step.prop] : null;
    /* Показываем шаг, если есть из чего выбирать (≥2 значения) ИЛИ сохранено значение, которого в
       текущем отборе нет (несовместимое/мёртвое из старого проекта): тогда шаг нужен, чтобы человек
       увидел и поправил его, а не чтобы «висящий» признак молча резал отбор в ноль (§7.1 — край
       обратной совместимости). Для каталога VIMAR «Форма» всегда одна и совместима → всегда скрыта. */
    if (values.length > 1 || (chosen && values.indexOf(chosen) < 0)) visible.push(step);
    if (chosen) above[step.prop] = chosen;
  });
  return visible;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { STEPS, stepOptions, visibleSteps };
if (typeof window !== "undefined") window.EPFramePicker = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
