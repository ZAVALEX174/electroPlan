/* Кнопочные накладки Flat и двойная плоская клавиша (К12 ч.4) — ЧИСТАЯ доменная логика над
   товаром и накладкой поста. Модуль без state, DOM и каталога: товары приходят аргументами, как
   mechColor.js/posts.js (PLAN 7.1). Здесь ОДНО место правила «сколько прорезей занимает изделие в
   КНОПОЧНОЙ накладке» (§7.1): его спрашивают и ёмкость окна поста, и раскладка, и фильтр каталога —
   второй копии правила нет, поэтому у правки нет краёв.

   --- ЧТО ТАКОЕ КНОПОЧНАЯ НАКЛАДКА -----------------------------------------------------------------
   У накладок Flat «на N кнопок» (базы 22682, 22683, 22684) прорези в один ряд рассчитаны на отдельные
   кнопки, и двойная плоская клавиша 22751 садится КАЖДЫМ своим квадратиком в ОТДЕЛЬНУЮ прорезь —
   значит занимает столько прорезей, сколько у неё кнопок (решение владельца 01.11). Вне кнопочных
   накладок (обычная 22681.1 и пр.) 22751 ведёт себя как раньше — один модуль.

   Признак кнопочной накладки — СПИСОК БАЗ в данных, а не регэксп по названию в рантайме (решение
   владельца 01.11): ровно 6 баз Flat, все цвета. База — часть артикула до цвета («22684.4.11» → база
   «22684.4»). Список намеренно включает и накладки «на 1 кнопку» (22682.1, 22683.1), но правило «по
   прорези на кнопку» применяется только там, где прорезей ≥ 2 (см. spanIn): у однопрорезной накладки
   двойной клавише вставать некуда, и её поведение не трогаем (владелец: вопрос заказчику).

   --- ПОЧЕМУ ПО БАЗЕ АРТИКУЛА, А НЕ ПО СЕРИИ/НАЗВАНИЮ ----------------------------------------------
   В каталоге рядом лежат Tondo-накладки с артикулом «22684.RN.4.*» («круглые отверстия», серия Eikon
   Tondo) — по названию «4 модуля» их легко спутать, но это НЕ кнопочные накладки. База «22684.4»
   их не захватывает: «22684.RN.4.11» с «22684.4.» не начинается. Клавишу 22751 узнаём тем же приёмом —
   по базе артикула «22751», а не по слову «две» в названии (его нет у всех 74 позиций одинаково). */
(() => {
"use strict";

/* Базы кнопочных накладок Flat (решение владельца 01.11): 6 баз, все цвета. В данных, в одном месте. */
const BUTTON_FRAME_BASES = ["22682.1", "22682.2", "22683.1", "22683.2", "22683.3", "22684.4"];

/* Совпадает ли артикул с базой: либо это сама база, либо база + разделитель «.» перед цветом.
   Граница по «.» обязательна — иначе «22684.4» поймало бы гипотетический «22684.41», а база
   «22684.4» не должна цеплять Tondo «22684.RN.4.*» (там после «22684.» идёт «RN», а не «4»). */
function codeHasBase(code, base) {
  const c = String(code || "");
  return c === base || c.startsWith(base + ".");
}

/* Число прорезей накладки — то же поле, что читают frameLayout/frameSlotCount (slotCount каталога).
   Нужно, чтобы правило «по прорези на кнопку» включалось только у накладок с ≥2 прорезями. */
function slotCountOf(frame) {
  return Number(frame && (frame.slotCount ?? frame.slots ?? frame.placeCount)) || 0;
}

/* Накладка-кнопочная: товар-накладка, чья база артикула в списке 6 баз Flat. kind проверяем, чтобы
   случайное совпадение артикула механизма с базой не выдало механизм за накладку. */
function isButtonFrame(frame) {
  if (!frame || (frame.kind && frame.kind !== "frame")) return false;
  return BUTTON_FRAME_BASES.some(base => codeHasBase(frame.code, base));
}

/* Сколько кнопок (отдельных квадратиков) у изделия. Двойная плоская клавиша 22751.* — две; у всего
   остального одна. Признак — база артикула «22751» (а не слово в названии): у всех 74 позиций 22751
   две кнопки, но название у них разное («две плоские клавиши», «…символ…», «…ON/OFF…»). */
function buttonsOf(item) {
  return item && codeHasBase(item.code, "22751") ? 2 : 1;
}

/* Ширина изделия в прорезях КОНКРЕТНОЙ накладки — ЕДИНСТВЕННОЕ выражение правила ёмкости для К12 ч.4.
   baseSpan — обычная ширина в модулях (EPCatalog.mechanismSpan), её передаёт вызывающий; второй раз
   считать название/поле здесь не нужно. В кнопочной накладке с ≥2 прорезями многокнопочное изделие
   занимает прорезь на кнопку (двойная клавиша → 2); всё прочее и любая накладка — baseSpan как раньше.
   Гвоздь обратной совместимости: baseSpan===0 (пропавший из каталога артикул, mechanismSpan(null)=0)
   проходит насквозь — его оценку в 1 модуль делают потребители (moduleLayout/tokenDeps `|| 1`), и
   мы её не перебиваем, иначе пробел посчитался бы иначе, чем соседний код. */
function spanIn(item, frame, baseSpan) {
  const base = Number(baseSpan) || 0;
  if (isButtonFrame(frame) && slotCountOf(frame) >= 2) {
    const buttons = buttonsOf(item);
    if (buttons > 1) return buttons;   // двойная клавиша — по прорези на кнопку
  }
  return base;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — module.exports для тестов. */
const api = { BUTTON_FRAME_BASES, isButtonFrame, buttonsOf, spanIn };
if (typeof window !== "undefined") window.EPButtonFrame = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
