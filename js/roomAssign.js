/* Критерий видимой метки «вне помещений». Чистая функция без state, DOM и EPConfig — все
   данные приходят аргументами, как и в остальных вынесенных модулях. Здесь намеренно только
   критерий метки: правило «в какой комнате точка» живёт в app.js (resolveRoomForPoint), а
   этот модуль отвечает лишь на вопрос «считать ли объект вне помещений».

   Интерфейс приложению — window.EPRoomAssign. */
(() => {
"use strict";

/* Критерий видимой метки «вне помещений» — ЕДИНСТВЕННЫЙ экземпляр правила (§7.1). Условие «объект
   без комнаты» жило двумя дословными копиями: в compactIcon (простановка при создании иконки) и в
   syncNoRoomClass (точечная синхронизация). Копии обязаны совпадать до буквы — разойдись они, метка
   замигает: создание иконки поставит одно, синхронизация другое. Сводим оба потребителя сюда.
   Помечаем ТОЛЬКО когда комнаты в проекте есть (roomCount>0): без комнат «вне помещений» у всего
   подряд было бы шумом. roomId==null (loose) намеренно ловит и undefined — «поля нет» = «нет комнаты». */
function isOutsideRooms(roomId, roomCount) {
  return roomCount > 0 && roomId == null;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { isOutsideRooms };
if (typeof window !== "undefined") window.EPRoomAssign = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
