/* Округление количества до целых упаковок (К6, решение владельца 22.10: «рассчитать кратно
   упаковке»). Поставщик отгружает товар коробками по N штук, и заказать 7 штук из упаковки по
   10 нельзя — берётся целая упаковка (10). Правило вынесено в ОТДЕЛЬНУЮ чистую функцию
   намеренно (§7.1): его зовёт лист «По артикулам» выгрузки Excel (К6а), а следом — КП и панель
   итогов (К6б). Будь оно вписано в один потребитель, у второго появился бы край с другим
   округлением, и смета разошлась бы с заказом.

   packRound(qty, pack) → количество, кратное упаковке, округлённое ВВЕРХ.
     qty  — нужное количество (штук);
     pack — размер упаковки (штук в коробке).
   Нет данных об упаковке (pack пуст / ноль / не число) → количество возвращается КАК ЕСТЬ, без
   округления: «упаковки не знаем» отличается от «упаковка = 1» — во втором случае округлять не на
   что, а в первом мы не вправе менять число. Нулевое/отрицательное qty тоже отдаём как есть
   (нечего укладывать в упаковки). qty дробным быть не должно (количества штучные), но на всякий
   случай Math.ceil даёт корректную верхнюю границу и для него. */
(() => {
"use strict";

function packRound(qty, pack) {
  const q = Number(qty);
  if (!Number.isFinite(q)) return qty;     // мусор на входе не превращаем в число молча
  const p = Number(pack);
  if (!Number.isFinite(p) || p <= 0) return q;   // упаковка неизвестна — количество не трогаем
  if (q <= 0) return q;                           // нечего заказывать — упаковок ноль
  return Math.ceil(q / p) * p;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — module.exports для
   автотестов (PLAN 7.1). */
const api = { packRound };
if (typeof window !== "undefined") window.EPPackRound = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
