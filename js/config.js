  gridSteps: [5, 10, 25, 50], // допустимые шаги сетки для выбора в UI и фильтра при restore
  snapRadius: 14,       // радиус магнита разметки, px (новое: привязка к концам и пересечениям линий)
  spaceCell: 10,        // размер ячейки при делении пространства (был параметр cell=10 в EPGeom.buildSpaceComponents)
  wallCellRadius: 7,    // на сколько px линия «засвечивает» ячейку как занятую (был wallRadius=7 там же)
  /* Бесконечный холст: сетку свободного пространства строим по bounding box
     нарисованного, а не по размеру блока. Запас вокруг содержимого и предохранитель
     на число клеток — чтобы сетка накрыла объекты, но не разрослась до зависания. */
  spaceMargin: 40,      // запас вокруг содержимого при построении сетки свободного места, px
  spaceMaxCells: 300000,// предохранитель: максимум клеток сетки (иначе укрупняем шаг) — большая сетка вешает UI
  /* Вид холста (viewport): границы зума и параметры «вписать в экран». */
  viewMinScale: 0.1,    // минимальный масштаб вида
  viewMaxScale: 4,      // максимальный масштаб вида
  viewZoomStep: 0.1,    // шаг кнопок +/− (доля масштаба на нажатие)
  viewFitPadding: 48,   // поля вокруг содержимого при «вписать в экран», px
  /* Порог начала переноса объекта, px экрана (PLAN: клик и перенос не должны спорить).
     Пока курсор не отошёл дальше — это клик, а не перенос: дрожание руки не сдвигает
     объект. 4–5 px — общепринятый порог; берём 4. */
  dragThreshold: 4,     // порог «клик vs перенос», px
  autosaveDelay: 700,   // задержка автосохранения, мс (был setTimeout(persistProject,700) в app.js)
  planDimOpacity: 0.25, // прозрачность подложки в «бледном» режиме (новое: Этап 1, три состояния видимости)

  /* Этап 3 — помещения из линий разметки (грани планарного графа, EPRoomsFromLines) */
  roomWeldTol: 0.75,    // допуск склейки узлов планарного графа, px: после магнитов координаты почти целые, но точное сравнение float опасно
  roomMinAreaPx: 100,   // порог отсечения вырожденных граней, px²: щели и «усы»-тупики дают крошечные/нулевые циклы
  roomAutoDelay: 600,   // задержка автопересчёта помещений после правки линий, мс (по образцу autosaveDelay)
