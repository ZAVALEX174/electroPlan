/* Единая точка для «магических чисел» интерфейса плана (PLAN 2.3). Значения по
   умолчанию ОБЯЗАНЫ совпадать с прежними константами в коде — иначе поедет уже
   работающая логика сетки, привязок и автосохранения. Смысл модуля в том, чтобы
   менять число в одном месте, а не выискивать его по файлам.

   Важно: чистая геометрия (js/geometry.js) намеренно НЕ читает этот конфиг — она
   получает размеры и радиусы аргументами и остаётся тестируемой без окружения.
   Значения сюда подставляет оркестратор app.js. */
(() => {
"use strict";

const api = {
  /* Шаг привязочной сетки теперь настройка проекта (state.gridStep), а не константа:
     владелец просил уметь менять его и по умолчанию мельче прежних 25 px. Здесь —
     только дефолт и допустимый набор значений (валидация выбора и восстановления). */
  gridDefault: 10,      // шаг сетки по умолчанию, px (был 25; владелец: мельче)
  gridSteps: [5, 10, 25, 50], // допустимые шаги сетки для выбора в UI и фильтра при restore
  snapRadius: 14,       // радиус магнита разметки, px (новое: привязка к концам и пересечениям линий)
  spaceCell: 10,        // размер ячейки при делении пространства (был параметр cell=10 в EPGeom.buildSpaceComponents)
  wallCellRadius: 7,    // на сколько px линия «засвечивает» ячейку как занятую (был wallRadius=7 там же)
  autosaveDelay: 700,   // задержка автосохранения, мс (был setTimeout(persistProject,700) в app.js)
  planDimOpacity: 0.25, // прозрачность подложки в «бледном» режиме (новое: Этап 1, три состояния видимости)

  /* Этап 3 — помещения из линий разметки (грани планарного графа, EPRoomsFromLines) */
  roomWeldTol: 0.75,    // допуск склейки узлов планарного графа, px: после магнитов координаты почти целые, но точное сравнение float опасно
  roomMinAreaPx: 100,   // порог отсечения вырожденных граней, px²: щели и «усы»-тупики дают крошечные/нулевые циклы
  roomAutoDelay: 600,   // задержка автопересчёта помещений после правки линий, мс (по образцу autosaveDelay)
  roomMaxSegments: 400, // предохранитель: максимум линий разметки на входе — обход O(n²)/O(n³) не должен вешать UI на патологическом вводе
  roomMaxFaces: 200,    // предохранитель: максимум найденных граней-помещений в одном пересчёте
  roomSimplifyEps: 6    // эпсилон упрощения контура (Дуглас-Пекер) в запасном проходе по сетке, px
};

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports, чтобы значения были доступны и в автотестах. */
if (typeof window !== "undefined") window.EPConfig = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
