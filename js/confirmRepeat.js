/* Подтверждение необратимой команды — одна механика на всё приложение.

   ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Системный confirm() в проекте не используется, поэтому необратимые
   команды («перенумеровать посты», «закрыть конструктор без сохранения») спрашивают
   подтверждение сами. Пока это было двумя копиями «запомнили Date.now() — сравнили с окном»,
   обе копии несли ОДИН И ТОТ ЖЕ ДЕФЕКТ: у окна была верхняя граница и не было НИЖНЕЙ. Обычный
   двойной клик (два нажатия за 4 мс) и автоповтор зажатой клавиши (Esc, ~30 мс между
   срабатываниями) проходили оба нажатия мгновенно: человек не успевал прочитать предупреждение
   — оно ещё висело на экране, — а перенумерация групп света уже применилась или несохранённый
   пост уже закрылся.

   ⚠️ ЧТО ДЕЙСТВИТЕЛЬНО ОТЛИЧАЕТ ОСОЗНАННОЕ ДЕЙСТВИЕ ОТ ПОТОКА — ДРУГОЙ ЖЕСТ, А НЕ ДРУГОЕ ВРЕМЯ.
   Любая граница по времени поток только ЗАДЕРЖИВАЕТ: зажатая клавиша, автоповтор и нетерпеливые
   клики сыплют нажатиями бесконечно, и рано или поздно одно из них попадает в разрешённое окно
   — человек при этом ничего не решал, он просто не отпускал кнопку. Поэтому у модуля ДВА режима,
   и режим выбирает вызывающий по тому, есть ли ему куда поставить вторую кнопку:

   • ДВА ОРГАНА УПРАВЛЕНИЯ (via: "arm" / "confirm") — так работает перенумерация постов. Нажатие
     на саму команду ТОЛЬКО взводит вопрос и не применяет его НИКОГДА, сколько бы их ни пришло;
     применяет отдельная кнопка «Подтвердить», которой до вопроса на экране не было. Поток по
     исходной кнопке в неё физически не попадает — это и есть настоящая разница между решением и
     потоком. Ждать при этом не нужно ни секунды: прочитал — нажал соседнюю кнопку.
   • ПОВТОР ТОГО ЖЕ ДЕЙСТВИЯ (via не задан) — так работает закрытие конструктора по Esc, где
     второй кнопке взяться неоткуда. Здесь поток отсекается ПАУЗОЙ ПЕРЕД НАЖАТИЕМ (см. minMs):
     нижняя граница считается не от взвода, а ОТ ПРЕДЫДУЩЕГО НАЖАТИЯ, поэтому пока клавишу
     дёргают, подтверждения нет вовсе. Это то же правило, что «Esc с e.repeat не считается» в
     оркестраторе, только со стороны логики.

   ГРАНИЦЫ ОКНА.
   • Нижняя (minMs) — общая, 800 мс ТИШИНЫ ПЕРЕД НАЖАТИЕМ: заведомо больше системного интервала
     двойного клика (500 мс в Windows), интервала автоповтора клавиши (~30 мс) и темпа
     нетерпеливых кликов. Слишком раннее нажатие НЕ подтверждает и НЕ перевзводит подтверждение
     (окно продолжает идти от взвода, вопрос остаётся тем же) — оно лишь отодвигает тишину,
     которой требует следующее нажатие.
   • Верхняя (maxMs) — своя у каждого действия и считается ОТ ВЗВОДА: «ещё раз» через минуту это
     уже не то же действие. Задаёт вызывающий, потому что цена ошибки и объём чтения у команд
     разные.

   ПОДТВЕРЖДЕНИЕ ПРИВЯЗАНО К ТОМУ, ЧТО ПОКАЗАЛИ (subject). Голая метка времени не знала, ЧТО
   именно человеку обещали: между нажатиями проект можно изменить, и второе нажатие применяло
   пересчёт, про который показывали ДРУГИЕ числа. Поэтому взвод хранит подпись посчитанного, и
   если к следующему нажатию она стала другой — это НЕ подтверждение, а новый вопрос с новыми
   числами. Подпись передаёт вызывающий (ему одному известно, что он показал); без неё модуль
   сравнивает только время — так работают действия, у которых показывать нечего.

   Модуль ЧИСТЫЙ: ни DOM, ни таймеров, ни Date.now() внутри — время приходит аргументом,
   состояние взвода хранит вызывающий. Поэтому обе границы проверяются автотестом.

   Интерфейс приложению — window.EPConfirmRepeat. */
(() => {
"use strict";

/* Требуемая ТИШИНА ПЕРЕД подтверждающим нажатием (режим повтора): пока команду продолжают
   дёргать, осознанного решения не было — был поток. Одна на все команды. */
const MIN_MS = 800;

/* Кнопка подтверждения не принимает нажатие, пришедшее ОДНОВРЕМЕННО с её появлением.
   ⚠️ Это не «задержка на подумать», а защита от промаха: кнопка появляется рядом с командой, и
   разметка при этом слегка сдвигается — клик, нацеленный в саму команду, не должен из-за сдвига
   попасть в подтверждение. 250 мс человек не замечает (ему ещё читать предупреждение и вести
   мышь), а мгновенный «хвост» предыдущего клика отсекает целиком. Такое нажатие вопрос НЕ
   снимает — оно просто ничего не делает. */
const ARM_MS = 250;

/* press(armed, opts) → {action, armed}

   armed — состояние взвода вызывающего: null (не взведено) либо {at, last, subject} из прошлого
   ответа (at — когда взвели, last — когда команду дёргали в последний раз).
   opts = {now, maxMs, subject?, minMs?, armMs?, via?}.

   via — ЧЕМ нажали (см. два режима в шапке):
     не задано  — тем же органом управления, что и в первый раз (повтор действия, Esc);
     "arm"      — исходной командой, у которой есть отдельная кнопка подтверждения;
     "confirm"  — этой самой отдельной кнопкой.

   action:
     "arm"     — подтверждение взведено (первое нажатие, истёкшее окно или ДРУГАЯ подпись):
                 вызывающий показывает предупреждение и НИЧЕГО не делает;
     "wait"    — нажатие пришло раньше, чем через minMs ПОСЛЕ ПРЕДЫДУЩЕГО нажатия: это не
                 решение, а продолжение того же потока (автоповтор, дребезг, нетерпеливые
                 клики). Взвод сохраняется (то же время взвода, та же подпись), но отметка
                 последнего нажатия сдвигается на now — поэтому поток НЕ докликивается до
                 подтверждения, сколько бы ни длился, а первое же нажатие после паузы
                 подтвердит;
     "confirm" — подтверждено: действие выполняется, взвод снят (armed = null);
     "cancel"  — ТОЛЬКО для via:"confirm": подтверждать нечего или уже нечего (взвода нет, окно
                 истекло, часы уехали назад или проект изменился и показанные числа больше не
                 те). Вызывающий убирает кнопку подтверждения и НИЧЕГО не применяет. Отдельное
                 действие, а не "arm": человек не просил задать вопрос заново, он нажал на
                 кнопку, которой уже не место на экране.

   Ответ всегда несёт НОВОЕ состояние взвода — вызывающему остаётся его записать, и разойтись
   «что решили» и «что запомнили» не могут. */
function press(armed, opts) {
  const o = opts || {};
  const now = Number(o.now);
  const minMs = Number.isFinite(Number(o.minMs)) ? Number(o.minMs) : MIN_MS;
  const armMs = Number.isFinite(Number(o.armMs)) ? Number(o.armMs) : ARM_MS;
  const maxMs = Number(o.maxMs);
  const subject = o.subject;
  const via = (o.via === "arm" || o.via === "confirm") ? o.via : "repeat";
  const arm = { action: "arm", armed: { at: now, last: now, subject } };
  /* ⚠️ ИСХОДНАЯ КОМАНДА НЕ ПОДТВЕРЖДАЕТ НИКОГДА. Здесь и живёт защита от потока: сколько бы
     нажатий ни пришло на саму кнопку — хоть автоповтором, хоть нетерпеливыми кликами любого
     темпа — они только взводят вопрос заново. Применить может лишь ДРУГОЙ орган управления
     (via: "confirm"), в который поток по этой кнопке не попадает. */
  if (via === "arm") return arm;
  const cancel = { action: "cancel", armed: null };
  if (!armed || !Number.isFinite(Number(armed.at))) return via === "confirm" ? cancel : arm;
  /* Подпись сравнивается ТОЛЬКО когда её передали: действию без подписи (закрытие окна с
     несохранёнными правками) сравнивать нечего, и требовать её было бы выдумкой. */
  if (subject !== undefined && armed.subject !== subject) return via === "confirm" ? cancel : arm;
  const elapsed = now - Number(armed.at);
  /* Взвод из прошлой версии модуля (без last) читаем по времени взвода: у него первое нажатие
     и последнее — одно и то же. */
  const lastAt = Number.isFinite(Number(armed.last)) ? Number(armed.last) : Number(armed.at);
  const quiet = now - lastAt;
  /* Часы «уехали» назад (перевод времени, сон машины) — считаем взвод недействительным и
     спрашиваем заново: отрицательная разница не доказывает осознанности. */
  if (!Number.isFinite(elapsed) || elapsed < 0 || !Number.isFinite(quiet) || quiet < 0) return via === "confirm" ? cancel : arm;
  const expired = Number.isFinite(maxMs) && elapsed > maxMs;
  /* Кнопка подтверждения — уже ДРУГОЙ жест, и требовать от неё паузы «на подумать» незачем:
     поток по исходной команде до неё не доходит по построению. Остаются верхняя граница, подпись
     («подтверждают именно то, что показали») и защита от промаха первых ARM_MS. */
  if (via === "confirm") {
    if (expired) return cancel;
    if (elapsed < armMs) return { action: "wait", armed: { at: Number(armed.at), last: now, subject: armed.subject } };
    return { action: "confirm", armed: null };
  }
  /* Тишина перед нажатием — ГЛАВНАЯ проверка режима повтора, и она идёт ПЕРЕД верхней границей:
     нажатие из потока не должно ни подтверждать, ни перевзводить вопрос новыми числами (иначе
     достаточно было бы додёргать команду до конца окна и начать сначала — вопрос задавался бы
     вечно, а подтверждался бы всё равно потоком). */
  if (quiet < minMs) return { action: "wait", armed: { at: Number(armed.at), last: now, subject: armed.subject } };
  if (expired) return arm;
  return { action: "confirm", armed: null };
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { press, MIN_MS, ARM_MS };
if (typeof window !== "undefined") window.EPConfirmRepeat = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
