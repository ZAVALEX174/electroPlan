/* Подтверждение ПОВТОРОМ ТОГО ЖЕ ДЕЙСТВИЯ — одна механика на всё приложение.

   ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Своих модальных диалогов в приложении нет, а системный confirm() в
   проекте не используется, поэтому необратимые команды («перенумеровать посты», «закрыть
   конструктор без сохранения») спрашивают подтверждение вторым нажатием той же кнопки. Пока
   это было двумя копиями «запомнили Date.now() — сравнили с окном», обе копии несли ОДИН И ТОТ
   ЖЕ ДЕФЕКТ: у окна была верхняя граница и не было НИЖНЕЙ. Обычный двойной клик (два нажатия за
   4 мс) и автоповтор зажатой клавиши (Esc, ~30 мс между срабатываниями) проходили оба нажатия
   мгновенно: человек не успевал прочитать предупреждение — оно ещё висело на экране, — а
   перенумерация групп света уже применилась или несохранённый пост уже закрылся. Второе
   нажатие обязано быть ОСОЗНАННЫМ, а осознанное — это не «через 4 мс».

   ГРАНИЦЫ ОКНА.
   • Нижняя (minMs) — общая, 800 мс: заведомо больше системного интервала двойного клика
     (500 мс в Windows) и больше задержки автоповтора клавиши. Слишком раннее нажатие НЕ
     подтверждает и НЕ перевзводит подтверждение: взвод остаётся на своём времени, и следующее
     нажатие человека (уже прочитавшего предупреждение) сработает как надо.
   • Верхняя (maxMs) — своя у каждого действия: «ещё раз» через минуту это уже не то же
     действие. Задаёт вызывающий, потому что цена ошибки и объём чтения у команд разные.

   ПОДТВЕРЖДЕНИЕ ПРИВЯЗАНО К ТОМУ, ЧТО ПОКАЗАЛИ (subject). Голая метка времени не знала, ЧТО
   именно человеку обещали: между нажатиями проект можно изменить, и второе нажатие применяло
   пересчёт, про который показывали ДРУГИЕ числа. Поэтому взвод хранит подпись посчитанного, и
   если к следующему нажатию она стала другой — это НЕ подтверждение, а новый вопрос с новыми
   числами. Подпись передаёт вызывающий (ему одному известно, что он показал); без неё модуль
   сравнивает только время — так работают действия, у которых показывать нечего.

   Модуль ЧИСТЫЙ: ни DOM, ни таймеров, ни Date.now() внутри — время приходит аргументом,
   состояние взвода хранит вызывающий. Поэтому обе границы проверяются автотестом.

   Интерфейс приложению — window.EPConfirmRepeat. */
(() => {
"use strict";

/* Нижняя граница окна: раньше — это не второе осознанное действие, а хвост первого
   (двойной клик, автоповтор клавиши, дрожание руки). Одна на все команды. */
const MIN_MS = 800;

/* press(armed, opts) → {action, armed}

   armed — состояние взвода вызывающего: null (не взведено) либо {at, subject} из прошлого
   ответа. opts = {now, maxMs, subject?, minMs?}.

   action:
     "arm"     — подтверждение взведено (первое нажатие, истёкшее окно или ДРУГАЯ подпись):
                 вызывающий показывает предупреждение и НИЧЕГО не делает;
     "wait"    — нажатие пришло раньше нижней границы: это не подтверждение. Взвод сохраняется
                 как был (то же время, та же подпись) — вызывающий показывает то же
                 предупреждение ещё раз, и следующее нажатие подтвердит;
     "confirm" — осознанный повтор в границах окна и с той же подписью: действие выполняется,
                 взвод снят (armed = null).

   Ответ всегда несёт НОВОЕ состояние взвода — вызывающему остаётся его записать, и разойтись
   «что решили» и «что запомнили» не могут. */
function press(armed, opts) {
  const o = opts || {};
  const now = Number(o.now);
  const minMs = Number.isFinite(Number(o.minMs)) ? Number(o.minMs) : MIN_MS;
  const maxMs = Number(o.maxMs);
  const subject = o.subject;
  const arm = { action: "arm", armed: { at: now, subject } };
  if (!armed || !Number.isFinite(Number(armed.at))) return arm;
  /* Подпись сравнивается ТОЛЬКО когда её передали: действию без подписи (закрытие окна с
     несохранёнными правками) сравнивать нечего, и требовать её было бы выдумкой. */
  if (subject !== undefined && armed.subject !== subject) return arm;
  const elapsed = now - Number(armed.at);
  /* Часы «уехали» назад (перевод времени, сон машины) — считаем взвод недействительным и
     спрашиваем заново: отрицательная разница не доказывает осознанности. */
  if (!Number.isFinite(elapsed) || elapsed < 0) return arm;
  if (elapsed < minMs) return { action: "wait", armed };
  if (Number.isFinite(maxMs) && elapsed > maxMs) return arm;
  return { action: "confirm", armed: null };
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { press, MIN_MS };
if (typeof window !== "undefined") window.EPConfirmRepeat = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
