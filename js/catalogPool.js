/* ПУЛ С ЗАПАСОМ ИЗ СНЯТЫХ (Д2) — одно правило на весь автоподбор детали поста.

   Решение владельца: позиции, убранные заказчиком из номенклатуры, в НОВЫЕ посты не предлагаются,
   но в СОХРАНЁННЫХ проектах остаются с последней ценой. Автоподбор детали (суппорт, подсветка,
   голый механизм за клавишей, коробка) раньше видел только АКТИВНЫЙ каталог (byKind фильтрует
   active), и всё, что пересчитывается на лету, снятых не находило: сохранённый пост получал null
   вместо суппорта, пропадал вариант подсветки 120 В. При этом подставлять снятую позицию ВМЕСТО
   активной нельзя — активная всегда главнее (иначе новый пост получил бы снятую деталь, которая
   к тому же бывает дешевле и выиграла бы обычный подбор).

   Отсюда ДВУХПРОХОДНОЕ правило, ОДНО на всех потребителей (§7.1 — иначе у правки будут края):
     1) подбираем по АКТИВНЫМ;
     2) только если среди активных подходящей НЕ нашлось — подбираем по активным ВМЕСТЕ со снятыми.
   Где активная деталь есть — снятые не смотрим вовсе, и для новых постов ничего не меняется.
   Снятая деталь и так помечается «снята с производства» в документах (как у В23).

   pick(select, active, extra, isFound):
     • select(pool) — чистый подбор на переданном списке (замыкание потребителя);
     • active — активные кандидаты, extra — снятые (запас);
     • isFound(result) — «подбор состоялся» (у каждого потребителя своя форма ответа: товар,
       {support}, {product}; поэтому решает вызывающий, а не этот модуль). Для случаев, когда
       пустой ответ ЗАКОНЕН (деталь не требуется, активная неоднозначность — выбор за человеком),
       isFound обязан вернуть true на первом проходе: тогда запас из снятых не подключается.
   Второй проход не делаем, если запас пуст, — ответ первого прохода и есть итог.

   Чистая функция, без DOM/state. Браузеру — window.EPCatalogPool, Node — module.exports. */
(() => {
"use strict";

function pick(select, active, extra, isFound) {
  const act = Array.isArray(active) ? active : [];
  const ext = Array.isArray(extra) ? extra : [];
  const first = select(act);
  const ok = isFound || (r => r != null);
  if (ok(first) || !ext.length) return first;
  /* запас из снятых подключаем, НЕ теряя приоритет активных: передаём активные + снятые,
     чтобы при равной пригодности активная всё равно могла выиграть обычным подбором. */
  return select(act.concat(ext));
}

const api = { pick };
if (typeof window !== "undefined") window.EPCatalogPool = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
