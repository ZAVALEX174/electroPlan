/* Подбор светодиода подсветки ПО ТИПУ КЛАВИШИ (ОЗ-1, заказчик Вадим 20.10).
   ------------------------------------------------------------------------------------
   Правило разбито заказчиком по двум критериям: НАПРЯЖЕНИЕ (низковольтная 12-24 В /
   высоковольтная 230 В) и ТИП МЕХАНИЗМА (осевой / обычный / LINEA). Единая чистая функция,
   чтобы у правила не было краёв (§7.1 HANDOFF): и состав поста, и КП, и лист монтажника, и
   Excel, и сводная берут результат ОТСЮДА, а не решают каждый сам.

   ПОЧЕМУ НЕ ПО ПОЛЮ askBacklight КАТАЛОГА. Поле askBacklight/backlightPosition в
   номенклатуре для многих клавиш проставлено неверно или отсутствует: у всех Eikon
   20021/20022/20023/20026 оно false, у цветных и металлических вариантов Arke (19021.C.B и
   т.п.) тоже false, у осевых Plana 14131/14132 и у ВСЕХ клавиш LINEA — false, а у светодиодов
   LINEA 00941/00943 нет ни цвета, ни позиции. Заказчик прямо сказал «021/022/023 любых
   индикаций», поэтому тип определяем САМИ — по серии и семейству артикула клавиши, а каталог
   как источник признака «принимает подсветку» не используем.

   КЛАССЫ (решения владельца/оркестратора, менять нельзя):
     · ordinary — обычные клавиши 021/022/023 (любые индикации) и 026 с окошком → светодиод
       внизу: 00935.* (12-24 В) / 00936.250.* (230 В);
     · axial    — осевые клавиши (Plana 14131/14132, осевые устройства 19108/19113/20101/
       20105/20108/20113, Flat 22751 с символами, Tondo 22761.RN) → светодиод по центру:
       00937.* (12-24 В) / 00938.* (230 В);
     · linea    — ВСЕ клавиши LINEA 31000/31000A/31000S → ТОЛЬКО светодиоды LINEA:
       00941.* (12-24 В) / 00943.* (230 В). Светодиоды LINEA не ставятся к другим сериям, а к
       LINEA — никогда светодиоды других серий (универсальный LED LINEA на все типы клавиш);
     · none     — подсветку не принимает (в т.ч. Flat без символов 22751.0, Flat KNX/автоматики
       22751.RN и LINEA 31506 для кнопок — решение владельца: не включаем).
   Напряжения: 12-24 В и 230 В — два критерия заказчика; 120 В сохранено отдельным семейством
   (00936.120.* из снятых) ТОЛЬКО для обратной совместимости сохранённых проектов (решение Д2),
   у осевых/LINEA на 120 В — честный пробел, как было в старом подборе.

   ФОЛБЭК ОБРАТНОЙ СОВМЕСТИМОСТИ. Клавишу, которую шаблоны/списки выше не распознали, но каталог
   УЖЕ пометил askBacklight с монтажной позицией, относим по позиции (2 — осевая, 3 — обычная):
   так уже-размеченные семейства (осевые устройства 19108/20101…, снятые Arke 19101/19105) не
   теряют подсветку и не нужно перечислять каждое осевое семейство. Явные исключения правила
   (всё LINEA кроме 31000*, 22751.0, 22751.RN, 31506) главнее фолбэка. */

(function () {
  "use strict";

  /* Семейство светодиода по классу клавиши и напряжению проекта. Артикул цвета достраивается
     суффиксом (см. COLOR_SUFFIX): например ordinary + 230 В + «Белая» → 00936.250.W. */
  const LED_FAMILY = {
    // 120V — только обычные клавиши и только из снятых (Д2); у осевых/LINEA 120 В нет (честный пробел).
    ordinary: { "12-24V": "00935",    "120V": "00936.120",    "110-250V": "00936.250" },
    axial:    { "12-24V": "00937",    "110-250V": "00938" },
    linea:    { "12-24V": "00941",    "110-250V": "00943" }
  };

  /* Цвет подсветки проекта (как его отдаёт каталог в backlightColor и селектор проекта) →
     буква в суффиксе артикула светодиода. Тёплый белый (WW) в проекте не выбирается
     (у 00935.WW нет backlightColor), поэтому в карту не входит. */
  const COLOR_SUFFIX = {
    "Янтарная": "A",
    "Голубая":  "B",
    "Зелёная":  "G",
    "Красная":  "R",
    "Белая":    "W"
  };

  /* Осевые клавиши Plana 14131/14132: каталог их подсветку НЕ размечает (askBacklight=false),
     поэтому заданы явным списком. Прочие осевые семейства (19108/20101…) каталог метит
     askBacklight с позицией 2 и их ловит фолбэк по backlightPosition — перечислять их не нужно. */
  const AXIAL_BASES = ["14131", "14132"];

  const baseOf = code => String(code || "").split(".")[0];
  const segOf = (code, i) => String(code || "").split(".")[i];
  const isLinea = mech => !!(mech && mech.series && mech.series.indexOf("Linea") !== -1);

  /* Класс подсветки клавиши: "ordinary" | "axial" | "linea" | "none". Сперва правила заказчика
     по серии и семейству артикула, затем — фолбэк по askBacklight/backlightPosition каталога
     для уже-размеченных клавиш (см. шапку модуля). */
  function classify(mech) {
    if (!mech || mech.kind !== "mechanism") return "none";
    const code = String(mech.code || "");
    const base = baseOf(code);
    if (isLinea(mech)) {
      // LINEA: подсветку принимают только клавиши 31000/31000A/31000S; 31506 (для кнопок) и прочие
      // LINEA-механизмы — нет. Исключение главнее фолбэка (к LINEA — только светодиоды LINEA).
      if (base === "31000" || base === "31000A" || base === "31000S") return "linea";
      return "none";
    }
    // Flat: без символов (22751.0.*) подсветку не принимает; с любыми символами — осевая.
    // 22751.RN — клавиши для KNX/автоматики, проект их не комплектует (BYME/KNX не трогаем).
    if (base === "22751") return (segOf(code, 1) === "0" || segOf(code, 1) === "RN") ? "none" : "axial";
    // Tondo: осевыми подсвечиваются только 22761.RN.*
    if (base === "22761") return segOf(code, 1) === "RN" ? "axial" : "none";
    // Обычные клавиши 021/022/023 (любая индикация и цвет) и 026 с окошком → светодиод внизу.
    if (/^\d{2}(?:021|022|023|026)$/.test(base)) return "ordinary";
    // Осевые Plana 14131/14132 (каталог их не метит) — явным списком.
    if (AXIAL_BASES.indexOf(base) !== -1) return "axial";
    // Фолбэк: клавиша не распознана выше, но каталог пометил её askBacklight с позицией → по позиции.
    if (mech.askBacklight) {
      const pos = Number(mech.backlightPosition);
      if (pos === 2) return "axial";
      if (pos === 3) return "ordinary";
    }
    return "none";
  }

  /* Механизм принимает подсветку? — любой класс, кроме none. Этим признаком backlightPlan
     отличает «не клавиша, пропускаем» от «клавиша, но LED не подобран» (честный пробел). */
  function accepts(mech) {
    return classify(mech) !== "none";
  }

  /* Подбор аксессуара-светодиода под механизм.
     opts = { mechanism, color, voltage, accessories:[…товары] }.
     Возвращает товар-светодиод или null. null (а не «похожий»), если: класс none, не заданы
     цвет/напряжение, под это напряжение у класса нет семейства, или нужного артикула нет в пуле. */
  function pick(opts) {
    const o = opts || {};
    const cls = classify(o.mechanism);
    if (cls === "none") return null;
    const color = o.color, voltage = o.voltage;
    if (!color || !voltage) return null;          // без желаемых цвета/напряжения выбор недостоверен
    const family = (LED_FAMILY[cls] || {})[voltage];
    const suffix = COLOR_SUFFIX[color];
    if (!family || !suffix) return null;          // нет семейства под напряжение или неизвестный цвет
    const wantCode = family + "." + suffix;
    const list = o.accessories || [];
    return list.find(a => a && a.kind === "accessory" && String(a.code) === wantCode) || null;
  }

  /* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — module.exports
     для автотестов (PLAN 7.1). */
  const api = { classify, accepts, pick, LED_FAMILY: LED_FAMILY, COLOR_SUFFIX: COLOR_SUFFIX };
  if (typeof window !== "undefined") window.EPBacklightPick = api;
  if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
