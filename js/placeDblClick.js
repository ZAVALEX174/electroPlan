/* В19 (решение владельца 03.10): в режиме «Разместить» двойной клик по иконке стоящего поста =
   «открыть ЭТОТ пост», как и вне размещения. Новый пост НЕ появляется, открывается конструктор
   СТАРОГО. Одинарный клик по иконке по-прежнему ставит новый пост (В11, eb93dbe).

   ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. По правилу В11 ПЕРВЫЙ клик двойного уже поставил новый пост поверх
   старого (в 4 px) и вышел из размещения; второй клик + браузерный dblclick прилетают по НОВОМУ
   посту. Чтобы вернуть жесту прежний смысл, app.js запоминает последнюю постановку, сделанную
   кликом по иконке существующего поста, а решение «это ли продолжение того двойного клика» выносим
   сюда — чистой функцией под мутационный тест. DOM, state и само удаление/открытие остаются в
   app.js; здесь нет ни того, ни другого — всё приходит аргументами (конвенция проекта, §7.1).

   ⚠️ ОКНО ПО ВРЕМЕНИ — ЕДИНСТВЕННЫЙ СПОСОБ ОТЛИЧИТЬ продолжение двойного клика от отдельного,
   осознанного двойного клика по НОВОМУ посту много позже. Браузер шлёт dblclick только когда два
   нажатия пришли за системный интервал двойного клика (в Windows 500 мс); к моменту dblclick от
   постановки прошло не больше этого интервала. Если же человек поставил пост кликом по иконке, а
   двойным кликнул новый пост спустя секунды — это уже «открыть новый пост», откатывать нельзя.
   Граница (WINDOW_MS) с запасом над системным интервалом, как ARM_MS/MIN_MS в confirmRepeat.

   Интерфейс приложению — window.EPPlaceDblClick. */
(() => {
"use strict";

/* Окно, в пределах которого dblclick считается продолжением постановки кликом по иконке.
   Больше системного интервала двойного клика (500 мс) с запасом на медленную машину/перерисовку
   плана первым кликом; отдельный двойной клик позже в него не попадает. */
const WINDOW_MS = 1000;

/* resolve(placement, postId, now, windowMs?) → решение для двойного клика по иконке поста.

   placement — последняя постановка, сделанная кликом по иконке стоящего поста, либо null:
     {newId, overId, t} — id нового поста, id старого (по чьей иконке кликнули), метка времени.
   postId — пост, по иконке которого пришёлся этот dblclick.
   now    — текущая метка времени (Date.now() в app.js; аргументом — ради мутационного теста).
   windowMs — окно продолжения двойного клика (по умолчанию WINDOW_MS).

   Возвращает:
     {undo:true,  removeId, openId} — это продолжение того двойного клика: убрать новый пост
                                      (removeId) и открыть старый (openId);
     {undo:false, openId}           — обычный двойной клик: открыть ЭТОТ пост (openId=postId). */
function resolve(placement, postId, now, windowMs) {
  const win = Number.isFinite(Number(windowMs)) ? Number(windowMs) : WINDOW_MS;
  if (placement && placement.newId === postId) {
    const elapsed = Number(now) - Number(placement.t);
    /* elapsed в пределах окна и неотрицателен (часы не уехали назад) — откатываем. */
    if (Number.isFinite(elapsed) && elapsed >= 0 && elapsed < win)
      return { undo: true, removeId: postId, openId: placement.overId };
  }
  return { undo: false, openId: postId };
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — module.exports для тестов. */
const api = { resolve, WINDOW_MS };
if (typeof window !== "undefined") window.EPPlaceDblClick = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
