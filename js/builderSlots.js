/* Слоты конструктора поста: механизм + ГРУППА СВЕТА клавиши, стоящей в этом слоте (C8).

   ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Группа света задаётся КЛАВИШЕ, то есть позиции в посте, а конструктор
   свой массив механизмов и переставляет (renderBuilder принимает упакованный порядок из
   EPPosts.distributePosts), и фильтрует (EPPosts.fitMechanismIds выкидывает чужие для набора и
   не влезающие). Параллельный массив «группа по индексу клавиши» после любой из этих операций
   указывал бы НЕ НА ТУ клавишу — и модуль групп света посчитал бы деньги по чужим местам, ничего
   не сообщив. Дублировать здесь упаковку с возвратом (packAll) ради переноса групп нельзя тем
   более: вторая копия правил раскладки рано или поздно разойдётся с первой.

   РЕШЕНИЕ — ТОКЕНЫ ПОЗИЦИЙ. Алгоритмы EPPosts работают со списком id товаров; мы даём им вместо
   id ПОЗИЦИИ слотов (0,1,2…) и подменяем чтение каталога (deps.product) на «токен → товар этого
   слота». Токены уникальны даже когда в посте два одинаковых механизма, поэтому ответ EPPosts —
   это перестановка/подмножество ПОЗИЦИЙ, по которой слоты (вместе с группами) собираются
   обратно один в один. Логика раскладки при этом остаётся ОДНА, в EPPosts, — здесь только
   переходник, и он проверяется автотестом.

   Модуль ЧИСТЫЙ: ни DOM, ни state, ни EPPosts (его функции зовёт оркестратор, передавая сюда
   готовый ответ). Интерфейс приложению — window.EPBuilderSlots. */
(() => {
"use strict";

/* Группа света — свободная строка человека («Кухня», «4.1», «71 72»).
   ⚠️ ТОЛЬКО СТРОКА, НИКОГДА ЧИСЛО: 4.10 в JS это 4.1, и группа «4.10» с плана заказчика слилась
   бы с «4.1» — две разные группы стали бы одной, а два выключателя (20.26 €) — двумя
   переключателями (25.79 €). Поэтому и здесь, и в поле ввода интерфейса значение живёт строкой,
   а нормализацию написания делает уже EPLightingGroups.normalizeGroup. */
const groupText = v => (v === null || v === undefined) ? "" : String(v);
/* Номер проходной — тоже свободная строка человека, и ТОЖЕ только строка: 4.10 в JS это 4.1, и
   проходная «4.10» слилась бы с «4.1» (та же ловушка, что у имени группы). */
const crossText = groupText;
/* Выбор механизма руками (ВАРИАНТ C): строка-роль либо пусто «как посчитано». */
const mechText = v => (v === null || v === undefined) ? "" : String(v);

/* Слот: id механизма (число, как в post.mechanismIds) + группа света + НОМЕР ПРОХОДНОЙ + выбранный
   РУКАМИ механизм. Всё это — свойства КЛАВИШИ, стоящей в слоте, и хранятся ВМЕСТЕ с механизмом, а не
   в параллельных массивах: перестановка/фильтрация слотов (упаковка по постам, отсев чужой серии)
   иначе указала бы номером и выбором НЕ НА ТУ клавишу — и модуль групп посчитал бы связь и деньги по
   чужим местам, ничего не сообщив. В этом вся суть модуля, и она распространяется на все три поля. */
const slot = (id, group, cross, mech) => ({ id: Number(id), group: groupText(group), cross: crossText(cross), mech: mechText(mech) });

/* ОСТАВЛЯТЬ ЛИ ГРУППУ НА ЭТОМ МЕХАНИЗМЕ — ОДНО ПРАВИЛО НА ЧТЕНИЕ И НА ЗАМЕНУ.
   Группу назначают КЛАВИШЕ (место управления — только она, см. EPLightingPlan.collect), и поле
   для неё есть только у клавиши. Стоит группа на не-клавише — человек её не видит и убрать не
   может, а расчёт рано или поздно посчитает по ней деньги (см. replaceAt ниже).
   Предикат приложения отвечает ТРЁХЗНАЧНО, и третий ответ здесь принципиален:
     true            — клавиша, группа остаётся;
     false           — товар в каталоге ЕСТЬ и клавишей не является: группе стоять не на чем,
                       снимаем;
     null/undefined  — товара в каталоге НЕТ (артикул выпал из прайса — заказчик перезаливает
                       его до 7 раз в год). Это НЕ «не клавиша»: снять группу значило бы стереть
                       настоящее место управления, которое расчёт как раз обязан показать
                       пробелом «потерянная клавиша» (EPLightingPlan.collect, lostKey), не меняя
                       механизмы соседей. Группу оставляем.
   Предиката нет вовсе — модуль о каталоге не знает и группу сохраняет (старый контракт). */
const keepsGroup = (id, isKey) => typeof isKey !== "function" || isKey(id) !== false;

/* Слоты из сохранённого поста. keyGroups — массив групп, параллельный mechanismIds; у старых
   проектов его нет вовсе, и все группы приходят пустыми (это и есть верное поведение: клавиша без
   имени группы — самостоятельный выключатель, механизм ей подбирается молча, см.
   EPLightingGroups.resolveGroup; имя группы нужно лишь чтобы связать клавиши разных постов в
   проходную).

   ⚠️ ЧТЕНИЕ — ЭТО ЕЩЁ И МИГРАЦИЯ. Защита «группа не переживает замену клавиши на не-клавишу»
   (replaceAt) работала только ВПЕРЁД: осиротевшая группа, записанная в проект ДО неё, спокойно
   переживала полный цикл «открыть пост в конструкторе → Сохранить» — fromPost читал keyGroups
   как есть, toPost писал обратно. То есть в старых проектах фантомные места оставались лежать и
   оживали при первой же перезаливке прайса: артикул розетки из него пропадал, позиция с непустой
   группой становилась «потерянной клавишей», N группы вырастал, и ЧУЖИЕ, нетронутые посты
   переезжали с переключателя (25.79 €) на инвертор (42.33 €). Поэтому правило одно и то же и на
   входе, и на замене — здесь оно чинит уже записанные данные, там не даёт записать новые. */
function fromPost(post, isKey) {
  const p = post || {};
  const ids = Array.isArray(p.mechanismIds) ? p.mechanismIds : [];
  const groups = Array.isArray(p.keyGroups) ? p.keyGroups : [];
  const crosses = Array.isArray(p.keyCrossNumbers) ? p.keyCrossNumbers : [];
  const mechs = Array.isArray(p.keyMechanisms) ? p.keyMechanisms : [];
  /* keepsGroup решает судьбу ВСЕХ полей клавиши разом: заменили клавишу на не-клавишу — и группа, и
     номер проходной, и ручной механизм снимаются вместе (стоять им не на чем, см. keepsGroup). */
  return ids.map((id, i) => {
    const keep = keepsGroup(id, isKey);
    return slot(id, keep ? groups[i] : "", keep ? crosses[i] : "", keep ? mechs[i] : "");
  });
}

/* Слоты → поля поста. keyGroups/keyCrossNumbers/keyMechanisms отдаём ВСЕГДА той же длины, что
   mechanismIds: массив короче («хвост пустой, зачем его хранить») развалил бы соответствие по
   индексу при первой же правке середины поста. */
function toPost(slots) {
  const list = Array.isArray(slots) ? slots : [];
  return { mechanismIds: list.map(s => Number(s.id)), keyGroups: list.map(s => groupText(s.group)),
    keyCrossNumbers: list.map(s => crossText(s.cross)), keyMechanisms: list.map(s => mechText(s.mech)) };
}

/* Есть ли в посте хоть одна заполненная группа — по этому признаку интерфейс и документы
   решают, показывать ли раздел групп света вообще. */
const hasGroups = slots => (Array.isArray(slots) ? slots : []).some(s => groupText(s && s.group).trim() !== "");

/* ─────────────────────── переходник к EPPosts ─────────────────────── */

/* Токены = позиции слотов. Именно они уходят в EPPosts вместо id товаров. */
const tokens = slots => (Array.isArray(slots) ? slots : []).map((_, i) => i);

/* Подмена чтения каталога: EPPosts спросит товар по «id», а получит товар слота с этим номером.
   mechanismSpan остаётся настоящим — ширина механизма от подмены не зависит.
   ⚠️ ПРОПАВШИЙ АРТИКУЛ = ПРОБЕЛ В 1 МОДУЛЬ. Когда товар слота исчез из каталога (product вернул
   null — прайс перезаливают до 7 раз в год), настоящий mechanismSpan(null) равен 0, и
   fitMechanismIds выбросил бы слот по ветке `!span` — тот же молчаливый обрыв, что и отсев по
   набору. Держим слот явным пробелом: у пропавшего товара ширину оцениваем в 1 модуль — ровно
   так же, как EPPosts.moduleLayout и distributePosts (у них та же оговорка `|| 1`), чтобы
   занятость, раскладка по постам и превью считали пробел одинаково и адреса соседних модулей
   не сдвинулись. У НАСТОЯЩЕГО механизма span всегда ≥ 1, поэтому `|| 1` срабатывает только на
   пропавшем артикуле и цену/ширину реальных товаров не трогает. */
function tokenDeps(slots, deps) {
  const list = Array.isArray(slots) ? slots : [];
  const d = deps || {};
  const product = d.product || (() => null);
  const span = d.mechanismSpan || (() => 1);
  return {
    product: token => {
      const s = list[Number(token)];
      return s ? product(s.id) : null;
    },
    mechanismSpan: item => Number(span(item)) || 1
  };
}

/* Список «разрешённых» для EPPosts.fitMechanismIds — но в токенах: слот проходит, если его товар
   есть в наборе items (совместимые с накладкой механизмы). Форма {id} — ровно та, что читает
   fitMechanismIds (он берёт у элементов только id).
   keepIds — артикулы, которые надо УДЕРЖАТЬ, даже если их нет в items: слоты, чей товар ПРОПАЛ из
   каталога (артикул исчез — товара нет вовсе). Это отдельное от items состояние: снятый с
   производства механизм товар имеет и приходит в items, а у пропавшего товара нет — считать
   нечего, но слот обязан остаться явным пробелом, иначе он молча выпадет из состава, цена упадёт
   и адреса соседних модулей сдвинутся (лист монтажника получит неверную нумерацию). Пустой keepIds
   → прежнее поведение (старый контракт: два аргумента). */
function allowedTokens(slots, items, keepIds) {
  const list = Array.isArray(slots) ? slots : [];
  const ids = new Set((Array.isArray(items) ? items : []).map(item => Number(item && item.id)));
  const keep = keepIds instanceof Set
    ? keepIds
    : new Set((Array.isArray(keepIds) ? keepIds : []).map(Number));
  const out = [];
  list.forEach((s, i) => { if (ids.has(Number(s.id)) || keep.has(Number(s.id))) out.push({ id: i }); });
  return out;
}

/* Ответ EPPosts (перестановка/подмножество токенов) → слоты. Токен вне диапазона молча
   пропускаем: сюда приходит результат чужой функции, и лишний undefined в слотах развалил бы
   и превью, и смету. */
function pick(slots, tokenList) {
  const list = Array.isArray(slots) ? slots : [];
  return (Array.isArray(tokenList) ? tokenList : [])
    .map(t => list[Number(t)])
    .filter(Boolean)
    .map(s => slot(s.id, s.group, s.cross, s.mech));
}

/* ─────────────────────── правки слотов ─────────────────────── */

/* Все три правки возвращают НОВЫЙ массив: конструктор перерисовывается целиком, и мутация
   исходного массива прятала бы источник изменений. Группа при замене механизма СОХРАНЯЕТСЯ —
   человек меняет клавишу «на 1 модуль» на «на 2 модуля» в том же месте той же группы, и
   заставлять его вводить группу заново значило бы терять данные на ровном месте. */
const add = (slots, id) => (Array.isArray(slots) ? slots : []).concat([slot(id, "", "", "")]);
const removeAt = (slots, index) => (Array.isArray(slots) ? slots : []).filter((_, i) => i !== Number(index));
/* replaceAt(slots, index, id, isKey?) — заменить механизм слота, сохранив его группу света.

   ⚠️ ГРУППА НЕ ПЕРЕЖИВАЕТ ЗАМЕНУ НА ИЗДЕЛИЕ, КОТОРОЕ МЕСТОМ УПРАВЛЕНИЯ НЕ ЯВЛЯЕТСЯ. Группу
   назначают КЛАВИШЕ (место управления — только она, см. EPLightingPlan.collect), и поле для
   неё есть только у клавиши. Заменили клавишу на розетку или фальшблок — группе не на чем
   стоять: в интерфейсе поля больше нет, человек её не видит и убрать не может, а в проекте она
   остаётся висеть на позиции, где клавиши уже нет. Это не безобидный мусор:
     • прайс перезаливают до 7 раз в год, и когда артикул этой розетки из него пропадёт,
       позиция с непустой группой станет «потерянной клавишей» (lostKey) — ФАНТОМНЫМ местом
       управления. N группы вырастет, и ЧУЖИЕ, нетронутые посты получат другие механизмы:
       проверено — сосед в той же группе переезжает с переключателя (25.79 €) на инвертор
       (42.33 €), хотя его никто не трогал;
     • обратная замена на клавишу молча воскрешает старую группу — и два независимых
       выключателя так же молча превращаются в проходную схему.
   isKey(id) — тот же трёхзначный предикат приложения, что и у fromPost (см. keepsGroup выше):
   решение «оставить или снять группу» обязано быть одним и тем же при чтении поста и при замене
   механизма, иначе конструктор снимал бы то, что чтение только что вернуло. */
function replaceAt(slots, index, id, isKey) {
  const list = Array.isArray(slots) ? slots : [];
  const i = Number(index);
  const keepGroup = keepsGroup(id, isKey);
  return list.map((s, j) => j === i
    ? slot(id, keepGroup ? s.group : "", keepGroup ? s.cross : "", keepGroup ? s.mech : "")
    : slot(s.id, s.group, s.cross, s.mech));
}
function setGroup(slots, index, group) {
  const list = Array.isArray(slots) ? slots : [];
  const i = Number(index);
  return list.map((s, j) => j === i ? slot(s.id, group, s.cross, s.mech) : slot(s.id, s.group, s.cross, s.mech));
}
/* Номер проходной и ручной механизм правятся так же точечно, сохраняя остальные поля слота. */
function setCross(slots, index, cross) {
  const list = Array.isArray(slots) ? slots : [];
  const i = Number(index);
  return list.map((s, j) => j === i ? slot(s.id, s.group, cross, s.mech) : slot(s.id, s.group, s.cross, s.mech));
}
function setMech(slots, index, mech) {
  const list = Array.isArray(slots) ? slots : [];
  const i = Number(index);
  return list.map((s, j) => j === i ? slot(s.id, s.group, s.cross, mech) : slot(s.id, s.group, s.cross, s.mech));
}

/* Снять группы со всего набора, сохранив сами механизмы.
   ⚠️ НУЖНО ДЛЯ ШАБЛОНА. Группа света — свойство ПОСТА НА ПЛАНЕ, а не шаблона: один и тот же
   шаблон («выключатель у двери») ставится в три комнаты, и это три РАЗНЫХ группы, а не одна
   с тремя местами управления. Шаблон, принесший свою группу, молча превратил бы три
   независимых выключателя (3 × 20.26 €) в проходную схему из двух переключателей и инвертора
   (25.79 + 25.79 + 42.33 €) — другая схема, другой монтаж и другие деньги. Поэтому конструктор
   шаблона открывает набор БЕЗ групп, а размещение на плане их не копирует. */
/* Снимаем и номер проходной, и ручной механизм вместе с группой: всё это — свойства ПОСТА НА ПЛАНЕ,
   не шаблона. Один шаблон в трёх комнатах — три разных проходных и три разных выбора механизма, а не
   один на всех (см. требование владельца: механизм — свойство клавиши размещённого поста). */
const clearGroups = slots => (Array.isArray(slots) ? slots : []).map(s => slot(s && s.id, "", "", ""));

/* Новая позиция слота после перестановки/фильтрации, выполненной через pick(): tokenList —
   ответ EPPosts (старые индексы в новом порядке), index — старый индекс. Слот выброшен → -1.
   ⚠️ ЗАЧЕМ. Конструктор помнит слот, помеченный «Заменить», НОМЕРОМ. Любая перерисовка,
   которая выкидывает слоты (смена накладки — чужой серии механизм отсеивается; смена числа
   модулей — не влезающий отсеивается) или переставляет их (упаковка по постам накладки),
   меняет смысл этого номера: пометка молча переезжает на слот, который человек не выбирал, и
   следующая карточка каталога заменяет ЧУЖОЙ механизм. Номер обязан ехать через ту же
   перестановку, что и сами слоты, — либо честно сбрасываться.
   Номер читается СТРОГО: целое число либо строка из одних цифр. Голый Number() здесь врал бы
   молча — Number("") и Number(null) равны нулю, и «цель не задана» становилась бы «цель —
   первый слот»: карточка каталога заменила бы механизм, которого человек не выбирал. */
function reindex(tokenList, index) {
  const list = Array.isArray(tokenList) ? tokenList : [];
  const i = typeof index === "number" ? index
    : (typeof index === "string" && /^\d+$/.test(index.trim()) ? Number(index.trim()) : NaN);
  if (!Number.isInteger(i) || i < 0) return -1;
  return list.findIndex(t => Number(t) === i);
}

/* Подпись набора — «изменился ли пост с момента открытия конструктора».
   Кодирование НЕСКЛЕИВАЕМОЕ (JSON), а не «id:группа через запятую»: имя группы вводит человек
   и в нём законно бывают и запятые, и двоеточия («Кухня, рабочая зона»), — склеенная подпись
   объявила бы два разных набора одинаковыми и потеряла бы правки без предупреждения. */
const signature = slots => JSON.stringify((Array.isArray(slots) ? slots : [])
  .map(s => [Number(s && s.id), groupText(s && s.group), crossText(s && s.cross), mechText(s && s.mech)]));

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { slot, fromPost, toPost, hasGroups, tokens, tokenDeps, allowedTokens, pick,
  add, removeAt, replaceAt, setGroup, setCross, setMech, clearGroups, reindex, signature };
if (typeof window !== "undefined") window.EPBuilderSlots = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
