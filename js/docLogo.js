/* Логотип компании в шапке документов (КП и лист монтажника) — ОДНО правило на оба (§7.1).
   У КП и листа монтажника шапки свёрстаны по-разному, но САМ элемент логотипа — как выглядит
   его <img>, какой у него печатный размер и, главное, что при отсутствии логотипа не должно
   остаться НИ пустого <img>, НИ дыры — обязан рисоваться из одного места. Иначе «пустая рамка»
   или другой размер прокрались бы в один документ и не в другой, и второй копии этого правила
   уже не отследить. Поэтому здесь: чистое решение «годен ли выбранный файл» и разметка элемента.

   Загрузку/ужатие картинки делает оркестратор (app.js) — там нужен DOM (FileReader/Image/canvas),
   а этот модуль без state и DOM, как offerPdf.js/installSheet.js: чистые функции проверяются
   автотестом, браузер не поднимая (PLAN 7.1).

   Интерфейс приложению — window.EPDocLogo.{ validateSource, imgHtml, MAX_SOURCE_BYTES }. */
(() => {
"use strict";

/* Честный предел исходного файла. Логотип-бланк — это герб/иконка, а не фотография: 5 МБ с
   огромным запасом покрывают любой разумный PNG/JPG/SVG, а всё крупнее почти наверняка не
   логотип (скан, фото с телефона) — незачем это ни декодировать, ни держать в LocalStorage.
   Проверяем ИСХОДНЫЙ файл до чтения: ужатие всё равно приведёт растр к печатной высоте, но
   отказать великану надо словами и сразу, а не молча проглотить и упереться в квоту хранилища. */
const MAX_SOURCE_BYTES = 5 * 1024 * 1024;

/* Годен ли ВЫБРАННЫЙ файл: это картинка и он в пределах размера. Возвращаем причину словами —
   оркестратор покажет её человеку и НЕ сохранит молча битое (решение владельца п.3). Читаем
   только file.type/file.size, поэтому функция чистая и проверяется без браузера. */
function validateSource(file) {
  if (!file || typeof file.type !== "string" || !/^image\//i.test(file.type)) {
    return { ok: false, reason: "Логотип должен быть картинкой — PNG, JPG или SVG" };
  }
  if (Number(file.size) > MAX_SOURCE_BYTES) {
    return { ok: false, reason: "Файл логотипа слишком большой — допустимо до 5 МБ" };
  }
  return { ok: true };
}

/* Элемент логотипа для шапки документа. Пусто или не data-URL картинки → "" (никакого пустого
   <img>: без логотипа шапка обязана выглядеть ровно как раньше). Принимаем только data:image/…:
   документы открываются через window.open, и внешний путь туда всё равно не доедет, а чужой src —
   лишний риск в уходящем клиенту документе.
   Геометрия — ИНЛАЙН-стилем, а не классом: строка одна на два документа с РАЗНЫМИ <style>,
   опереться на общий класс не на что, да и в окне печати наш CSS-класс из другого места не
   поможет. max-height держим заметно ниже растровой высоты, которую задаёт оркестратор при
   ужатии, — так в PDF (печать плотнее экрана) логотип остаётся чётким, а не мыльным.
   src экранируем (конвенция 4): валидный data-URL кавычек не содержит, но подстановка в
   разметку без esc недопустима по правилу. */
function imgHtml(logo, esc) {
  const src = typeof logo === "string" ? logo.trim() : "";
  if (!/^data:image\//i.test(src)) return "";
  const e = typeof esc === "function" ? esc : (s => String(s));
  return `<img src="${e(src)}" alt="Логотип компании" style="max-height:64px;max-width:240px;`
    + `object-fit:contain;display:block;margin:0 0 10px">`;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { validateSource, imgHtml, MAX_SOURCE_BYTES };
if (typeof window !== "undefined") window.EPDocLogo = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
