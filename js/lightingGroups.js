/* ─────────────────────── главный проход ─────────────────────── */

/* plan({ scheme, places }, deps) → распределение механизмов ПО МЕСТАМ.
   Отдаём именно распределение, а не итог по группе: механизмы одной группы стоят в РАЗНЫХ постах,
   и смете, листу монтажника и взрыв-схеме нужно знать, какой механизм в каком посте. Итоги по
   группе и по проекту приложены рядом, но они посчитаны ПО распределению, а не своей формулой.

   deps = {
     findMechanism({ role, series }) → товар|null                 // поиск по каталогу
     seriesOf(product) → [строки]                                 // необязательно
   }
   Контракт findMechanism СОЗНАТЕЛЬНО УЗКИЙ — только роль и серия. Место и группа ему не
   передаются: ответ обязан зависеть ровно от пары «роль+серия», иначе одна и та же клавиша дала
   бы в разных постах разные механизмы, а кэш ниже (ключ — та же пара) молча выдал бы ответ для
   первого спросившего. Понадобится подбор с оглядкой на место — расширять придётся ОДНОВРЕМЕННО
   и аргументы, и ключ кэша.
   findMechanism ОБЯЗАН вернуть null, если механизма такой роли в ЭТОЙ серии нет: подстановка
   чужой серии (клавиша Plana + механизм Eikon) — это неверная смета и невозможный монтаж.
   Модуль этого не проверяет и проверить не может — он не знает каталога; ответственность на deps.
   Серии приходят в findMechanism в НАПИСАНИИ САМОГО МЕСТА (приведены только пробелы, повторы и
   порядок — canonicalSeries). Регистр модуль не трогает и от deps регистронезависимости НЕ ТРЕБУЕТ:
   различает каталог написания или нет — знает только он, а ключ кэша здесь равен аргументу, так
   что каждое написание спрашивается отдельно и ответ на чужое написание не подставляется никому
   (см. большой комментарий про регистр серий выше). В нашем приложении подбор строится на
   catalog.js, а он сравнивает серии, приводя регистр у ОБЕИХ сторон (compatibleMechanisms), —
   для него это просто лишний вопрос к каталогу, а не другой ответ.
   Изделие findMechanism обязан вернуть С АРТИКУЛОМ (product.code): изделие без артикула модуль
   считает НЕ подобранным и ставит пробел NO_CODE — позиция с ценой и без артикула в смете хуже
   честного пробела.
   Исключение ИЗ ЛЮБОЙ ВНЕШНЕЙ ЗАВИСИМОСТИ наружу НЕ ПРОБРАСЫВАЕТСЯ: для модуля, вся идея
   которого «честный пробел вместо неверного числа», сбой каталога — это пробел LOOKUP_FAILED, а
   сбой чтения серии — пробел SERIES_FAILED, а не падение расчёта всего проекта. Правило одно на
   обе зависимости (см. readPlaceSeries): раньше исключение из seriesOf в тайбрейке порядка
   глотал try/catch, а в расчёте — роняло plan целиком, и один и тот же сбой давал то пробел, то
   исключение в зависимости от того, откуда пришёл вызов. */
function plan(input, deps) {
  const options = input || {};
  const d = deps || {};
  const list = Array.isArray(options.places) ? options.places : [];
  const schemeId = options.scheme || "classic";
  const scheme = schemeById(schemeId);
  const knownScheme = !!scheme;
  const supported = !!(scheme && scheme.supported);
  const seriesOf = d.seriesOf || defaultSeriesOf;
  const registry = buildRegistry(list, seriesOf);
  const order = registry.order;
  const duplicates = new Set(registry.duplicates);

  /* Кэш подбора: одна и та же роль в одной и той же серии спрашивается у каталога один раз.
     Не только ради скорости — так подстановка гарантированно одинакова во всех постах группы.
     В кэш кладём и ФАКТ ОШИБКИ: упавший поиск не повторяем на каждом месте и причину пробела
     называем ту же самую. Ключ — ровно те аргументы, что уходят в findMechanism (см. контракт).
     ⚠️ КЛЮЧ ОБЯЗАН БЫТЬ НЕСКЛЕИВАЕМЫМ. Раньше он собирался склейкой серий через запятую, и РАЗНЫЕ
     наборы серий давали ОДИН ключ: [«Eikon Evo,Eikon Exe»] (приложение передало серии одной
     строкой, не разбив по запятой) и [«Eikon Evo», «Eikon Exe»] — это разные вопросы к каталогу,
     а ключ у них совпадал. Место молча получало механизм, подобранный для ЧУЖОГО набора серий
     (прямое нарушение правила «чужую серию не подставляем» — неверная смета и невозможный
     монтаж), а второе место с честной серией — ложный пробел; что из двух случится, решал порядок
     входа. JSON-кодирование массива разделитель у элементов отнять не даёт.
     ⚠️ И ПО ТОЙ ЖЕ ПРИЧИНЕ КЛЮЧ РАВЕН АРГУМЕНТУ ПОБУКВЕННО: регистр серий в ключе НЕ приводится
     (см. большой комментарий про регистр серий выше). Пока ключ приводил регистр, а в
     findMechanism уходило исходное написание места, [«Eikon Evo»] и [«EIKON EVO»] были для кэша
     одним вопросом — и написание в этом вопросе выбирал первый ПО ВХОДУ спросивший: тот же
     проект давал 40.52 € при одном порядке мест и 0 € при другом. Ключ, равный аргументу, — это
     то же обещание «ответ зависит ровно от пары роль+серия», только проверяемое кодом. */
  const cache = new Map();
  const cacheKeyOf = (role, series) => JSON.stringify([role, series]);
  const lookup = (role, series) => {
    const key = cacheKeyOf(role, series);
    if (cache.has(key)) return cache.get(key);
    let result = { product: null, failed: false };
    if (d.findMechanism) {
      try { result = { product: d.findMechanism({ role, series }) || null, failed: false }; }
      catch (e) { result = { product: null, failed: true, error: e }; }
    }
    cache.set(key, result);
    return result;
  };

  /* Место в группе: индекс внутри группы (для формулы) и человекочитаемый номер «2 из 3».
     group.places уже в каноническом порядке — его и нумеруем. */
  const orderInGroup = new Map();   /* индекс места во входном списке → позиция внутри группы */
  registry.groups.forEach(group => group.places.forEach((placeIndex, i) => orderInGroup.set(placeIndex, i)));

  /* Разбор ОДНОГО места. Вынесен функцией не ради красоты: обход ниже идёт в каноническом
     порядке, а выдача остаётся на входных позициях — с телом «внутри map» это не собрать, не
     заведя второй копии правил. */
  const buildPlace = (raw, index) => {
    const place = raw || {};
    const key = groupKeyOf(place.group);
    const group = key ? registry.byKey.get(key) : null;
    const pos = orderInGroup.has(index) ? orderInGroup.get(index) : null;
    const counted = pos !== null;   /* место учтено в группе (не дубль, группа назначена) */
    /* Поля места в выдаче — ТЕ ЖЕ функции чтения, что и в опознании, порядке и реестре: то, что
       вызывающий видит в результате, обязано совпадать с тем, по чему модуль считал. */
    const out = {
      index,
      postId: postIdOf(place),
      postNumber: postNumberOf(place),
      keyIndex: keyIndexOf(place),
      keyId: keyIdOf(place),
      groupKey: group ? group.key : "",
      groupLabel: group ? group.label : "",
      placeNo: counted ? pos + 1 : null,          /* «место 2 из 3» для листа монтажника */
      placeCount: group ? group.placeCount : 0,
      role: null, roleLabel: null,
      product: null, code: null,
      missing: true, missingReason: null
    };

    /* Схема без правил (звонковые кнопки) или нераспознанный id — распределения нет вовсе.
       Причины РАЗНЫЕ: «схема описана в списке, но правил расчёта нет» — это ожидаемое состояние
       проекта с вопросом заказчику, а «такой схемы вообще нет» — ошибка данных. Один текст на
       оба случая врал бы про звонковые кнопки там, где схема просто битая. */
    if (!supported) { out.missingReason = knownScheme ? GAPS.SCHEME_NOT_READY : GAPS.SCHEME_UNKNOWN; return out; }

    /* Дубль места. ⚠️ НАШЕ РЕШЕНИЕ: повтор НЕ увеличивает число мест группы (первое место в
       каноническом порядке считается как обычно), но и не проглатывается молча — он становится
       ПРОБЕЛОМ с отдельной причиной. Молча игнорировать нельзя: вызывающий не узнает, что подал
       кривые данные. Считать местом — тем более: N вырос бы на ровном месте, выключатель
       превратился бы в два переключателя, а смета — подорожала бы за несуществующую клавишу. */
    if (duplicates.has(index)) { out.missingReason = GAPS.DUPLICATE_PLACE; return out; }

    /* Группа не назначена — подстановки НЕТ ни в одной схеме.
       ⚠️ НАШЕ ДОПУЩЕНИЕ (единое правило для обеих схем). Для классической иначе и нельзя: механизм
       там — функция от числа мест, а его без группы не существует. Для релейной кнопка формально от
       числа мест не зависит, и её можно было бы подставить сразу, — но тогда клавиша без группы
       попала бы в смету с ценой и НЕ попала бы в счёт реле, то есть документ получился бы
       наполовину правдивым. Плюс молчаливое подорожание уже сохранённых проектов: в старых проектах
       групп нет ни у одной клавиши. Одно правило «нет группы → нет подстановки, есть пометка»
       безопаснее и понятнее пользователю: интерфейс покажет, что именно дозаполнить.
       Проверка !counted — ПРЕДОХРАНИТЕЛЬ, а не второй случай: единственное, что не попадает в
       группу с непустым ключом, — это дубль, а он отсеян строкой выше. Отдельным тестом такое
       состояние не воспроизвести (потому и держится оно на конструкции, а не на проверке), но
       разойдись когда-нибудь реестр с этим проходом — пробел безопаснее места без позиции в
       группе: pos=null ушёл бы в roleFor и дал бы роль по несуществующему индексу. */
    if (!group || !counted) { out.missingReason = GAPS.NO_GROUP; return out; }

    const role = roleFor(schemeId, pos, group.placeCount);
    if (!role) { out.missingReason = GAPS.NO_ROLE; return out; }   /* предохранитель, см. isValidPlaceIndex */
    out.role = role;
    out.roleLabel = ROLE_LABELS[role];

    /* Серии — через ту же readPlaceSeries, что и ключ сортировки: одно чтение поля на весь модуль.
       Сбой deps.seriesOf — пробел SERIES_FAILED (внешняя зависимость упала), пустой ответ —
       NO_SERIES (серия просто не определена); причины разные, потому что чинят их разное. */
    const read = readPlaceSeries(place, seriesOf);
    const series = read.list;
    if (!series.length) { out.missingReason = read.failed ? GAPS.SERIES_FAILED : GAPS.NO_SERIES; return out; }
    out.series = series;

    const found = lookup(role, series);
    if (!found.product) {
      /* Механизма такой роли в серии клавиши нет — реальный случай: у Neve Up среди голых
         механизмов нет инвертора (09013 — готовое изделие с клавишей, не механизм под отдельную
         клавишу), значит классическая схема при N≥3 на этой серии не считается. Честный null и
         признак пробела — НЕ подстановка ближайшего похожего из чужой серии. */
      out.missingReason = !d.findMechanism ? GAPS.NO_LOOKUP
        : (found.failed ? GAPS.LOOKUP_FAILED : GAPS.NOT_IN_SERIES);
      return out;
    }

    /* ⚠️ ИЗДЕЛИЕ БЕЗ АРТИКУЛА — ЭТО НЕ ПОДОБРАННОЕ ИЗДЕЛИЕ. Раньше здесь стояло
       «code != null ? code : null», и место с изделием без артикула объявлялось успешным:
       missing=false, code=null. Это ровно та «правдоподобно неверная строка», которую модуль
       запрещает себе везде: позиция уходит в смету С ЦЕНОЙ и БЕЗ АРТИКУЛА, ни заказать, ни
       сверить её нельзя, а пробела не видит никто — ни счётчик missingTotal, ни список gaps.
       Артикул читаем тем же адресным полем, что и остальные идентификаторы места (addressFieldOf:
       края и внутренние пробелы, пусто → «не задано», не-идентификатор → «не задано»), — одно
       поле, одна функция чтения.
       out.product тоже остаётся null, и это не забывчивость: «подобрано» по всему модулю
       считается по p.product (см. roles/totals ниже), так что изделие с пробелом в выдаче
       посчиталось бы подобранным и вернуло бы ту же полуправду с другой стороны. */
    const code = productCodeOf(found.product);
    if (code === null) { out.missingReason = GAPS.NO_CODE; return out; }
    out.product = found.product;
    out.code = code;
    out.missing = false;
    return out;
  };

  /* ⚠️ ОБХОД ДЛЯ ПОДБОРА — В КАНОНИЧЕСКОМ ПОРЯДКЕ (order), а не по входному списку; выдача при
     этом остаётся на ВХОДНЫХ позициях (places[index]), и вызывающий читает результат по своему
     индексу как раньше. Ключ кэша, равный аргументу, уже избавил ОТВЕТЫ от зависимости от входа
     (см. cacheKeyOf), но пока очередь вопросов шла по входному списку, порядок входа оставался
     ВИДЕН каталогу — а всякая реализация deps с состоянием (счётчик, ленивая догрузка, свой кэш
     второго уровня, лог для отладки) на этом снова привязала бы смету к порядку. Теперь каталог
     видит один и тот же диалог: те же вопросы в том же порядке при любом входе.
     order — перестановка ВСЕХ индексов входного списка, включая дыры разреженного массива
     (canonicalOrder строит его через Array.from), поэтому дыр в выдаче не остаётся: длина
     places равна длине входа, каждое место разобрано ровно один раз. */
  const places = new Array(list.length);
  order.forEach(index => { places[index] = buildPlace(list[index], index); });

  /* Пробелы собираем ОТДЕЛЬНЫМ проходом в каноническом порядке. Если собирать их по ходу
     расчёта, и состав gaps[].places, и порядок самих записей следовали бы за порядком входного
     списка — та же болезнь, что и с раскладкой ролей. */
  const gaps = [];
  const addGap = gap => {
    /* groupKey нормализуем: у пробелов без группы поле не задано (undefined), а в сохранённой
       записи оно null — сравнение undefined с null НИКОГДА не истинно, и без этой строки каждая
       клавиша без группы плодила бы отдельную запись вместо одной общей. */
    const groupKey = gap.groupKey != null ? gap.groupKey : null;
    const same = gaps.find(g => g.kind === gap.kind && g.groupKey === groupKey);
    if (same) { same.places = same.places.concat(gap.places || []); return; }
    gaps.push(Object.assign({ groupKey: null, groupLabel: null, places: [], text: GAP_TEXTS[gap.kind] || "" },
      gap, { groupKey, places: (gap.places || []).slice() }));
  };

  if (!supported) {
    /* Пробел схемы — один на проект (а не по одному на клавишу): он про проект, а не про место.
       Ставится и на пустом проекте — интерфейсу надо показать причину, даже когда постов нет. */
    addGap({ kind: knownScheme ? GAPS.SCHEME_NOT_READY : GAPS.SCHEME_UNKNOWN, places: order.slice() });
  } else {
    order.forEach(index => {
      const p = places[index];
      if (!p.missingReason) return;
      const group = p.groupKey ? registry.byKey.get(p.groupKey) : null;
      addGap(group
        ? { kind: p.missingReason, groupKey: group.key, groupLabel: group.label, places: [index] }
        : { kind: p.missingReason, places: [index] });
    });
  }

  /* Итоги — ПОДСЧЁТОМ ролей в распределении, без второй формулы. Их ДВА, и это принципиально:
       rolesRequired / totalsRequired — сколько механизмов ТРЕБУЕТ СХЕМА (роль у места есть);
       roles / totals               — сколько РЕАЛЬНО ПОДОБРАНО (роль есть И изделие найдено).
     Раньше был один счётчик — «по схеме», и потребитель, читающий его как «сколько каких
     механизмов в проекте», строил смету со строками, которым не соответствует ни один артикул
     (тот самый инвертор Neve Up). В документы с ценами берут totals, в сообщение «чего не хватает»
     — разницу между required и totals; missing/missingTotal показывают её числом. */
  const emptyRoles = () => ({ [ROLES.SWITCH]: 0, [ROLES.CHANGEOVER]: 0, [ROLES.INVERTER]: 0, [ROLES.BUTTON]: 0 });
  const totals = emptyRoles();
  const totalsRequired = emptyRoles();
  let missingTotal = 0;
  const groups = registry.groups.map(group => {
    const roles = emptyRoles();
    const rolesRequired = emptyRoles();
    let missing = 0;
    group.places.forEach(i => {
      const p = places[i];
      if (p.role) { rolesRequired[p.role]++; if (p.product) roles[p.role]++; }
      if (p.missing) missing++;
    });
    return { key: group.key, label: group.label, placeCount: group.placeCount, places: group.places.slice(),
      posts: group.posts.map(p => ({ id: p.id, number: p.number, placeCount: p.placeCount })),
      roles, rolesRequired, missing };
  });
  places.forEach(p => {
    if (p.role) { totalsRequired[p.role]++; if (p.product) totals[p.role]++; }
    if (p.missing) missingTotal++;
  });

  /* Реле: считаем ПОТРЕБНОСТЬ числом и честно говорим, что артикула нет. Артикул 03992 из ТЗ в
     каталоге и номенклатуре VIMAR отсутствует (0 совпадений; «реле» в названиях — это IR-выключатели
     09181/19181/20181, другое изделие), а в накладной заказчика стоит стороннее реле Finder
     46.61.8.230.0040. Подставить сюда придуманный артикул с ценой = молча занизить/исказить смету;
     позиция без цены в спецификации даёт строку с нулём — оба варианта запрещены правилом проекта.
     Поэтому реле отдаётся отдельной секцией: количество есть, article = null, articleKnown = false.
     Считаем от ЧИСЛА МЕСТ (потребность по схеме), а не от числа подобранных кнопок: реле нужно
     проводке, даже если клавишу на каком-то месте подобрать не удалось. */
  const relays = schemeId === "relay"
    ? groups.map(g => ({ groupKey: g.key, groupLabel: g.label, buttonCount: g.placeCount,
        count: relayCount(g.placeCount), article: null, articleKnown: false,
        note: "Импульсное реле — артикул не определён" }))
    : [];
  const relayTotal = relays.reduce((sum, r) => sum + r.count, 0);
  if (relayTotal > 0) addGap({ kind: GAPS.RELAY_ARTICLE });

  return {
    scheme: schemeId,
    schemeLabel: scheme ? scheme.label : "",
    supported,
    places,
    order: order.slice(),          /* канонический порядок мест — тем, кто печатает по порядку плана */
    groups,
    unassigned: { placeCount: registry.unassigned.placeCount, places: registry.unassigned.places.slice() },
    duplicates: registry.duplicates.slice(),
    totals,
    totalsRequired,
    missingTotal,
    relays,
    relayTotal,
    gaps
  };
}

