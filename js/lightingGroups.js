/* Невидимые символы, которых человек в имени группы НЕ ВИДИТ, а строка их несёт: нулевой ширины
   (U+200B…U+200F, U+2060, U+FEFF) и мягкий перенос U+00AD. Приезжают копипастой из Word, Excel и
   PDF — а имена групп заказчик именно вбивает руками и копирует из чужих документов. Пока их не
   чистили, «Кухня» с невидимым символом внутри была ОТДЕЛЬНОЙ группой: два места одной группы
   разъезжались на две группы по одному месту, и вместо двух переключателей (25.79 € каждый)
   проект молча получал два выключателя (20.26 €) — неверная смета и другой монтаж. */
const INVISIBLE_CHARS = /[\u00AD\u200B-\u200F\u2060\uFEFF]/g;

/* Нормализация имени группы — это ТО, ЧТО ПЕЧАТАЕТСЯ. Группа — свободная строка, её вводит
   человек: в плане дизайнера встречаются и «71 72», и «4.1», и словами. Здесь чистка невидимого,
   юникод-нормализация, обрезка краёв и схлопывание внутренних пробелов — написание человека
   сохраняем как есть, а всё «склеивание разных написаний одной группы» делает groupKeyOf.
   Пустая строка = группа НЕ НАЗНАЧЕНА.
   ⚠️ ИМЯ ГРУППЫ — ЭТО СТРОКА ИЛИ ЧИСЛО (номер помещения с плана), и больше ничего. Раньше здесь
   стоял безусловный String(value), и объект превращался в «[object Object]»: ВСЕ объекты
   становились ОДНОЙ группой — чужие места в чужой группе, завышенный N и неверный механизм на
   ровном месте. Не-имя (объект, массив, boolean, NaN/Infinity, undefined) обязано давать пробел
   «группа не назначена», а не тихо слипаться с другими. */
function normalizeGroup(value) {
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "";
  if (typeof value !== "string") return "";
  /* NFC: «ё» и «й» бывают разложенными (е + U+0308, и + U+0306) — на вид те же буквы, но другая
     строка. Без нормализации «Спальня» из чужого документа и «Спальня», набранная руками, — две
     разные группы с одним местом в каждой вместо одной с двумя. */
  const text = value.replace(INVISIBLE_CHARS, "");
  const composed = typeof text.normalize === "function" ? text.normalize("NFC") : text;
  return composed.replace(/\s+/g, " ").trim();
}

/* Ключ группы — это ТО, ПО ЧЕМУ МЕСТА СХЛОПЫВАЮТСЯ В ОДНУ ГРУППУ, поэтому правило намеренно
   узкое: приводим только РЕГИСТР (пробелы уже привёл normalizeGroup). «Кухня», «кухня» и
   « Кухня  » — одна группа, иначе два места одной группы разъехались бы на две группы по одному
   месту и вместо двух переключателей проект молча получил бы два выключателя.
   ⚠️ СТРОКОВОЕ ИМЯ СОХРАНЯЕТ СВОЮ ФОРМУ и с другим строковым именем не сливается НИКОГДА.
   Раньше здесь стояла «канонизация числа» — у чисто числового имени срезались хвостовые нули
   дробной части, — и она СКЛЕИВАЛА РАЗНЫЕ ГРУППЫ: «4.10» и «4.1» становились одной. А у
   заказчика на планах номера групп записаны именно строками («71 72», «81 82 83», «4.1 4.2»),
   и «4.10» там — десятая группа, а не первая. Цена ошибки та же, что и у обратной: две разные
   группы по одному месту, склеенные в одну с N=2, дают два переключателя (25.79 €) вместо двух
   выключателей (20.26 €) — неверная смета и физически другой монтаж.
   ЧИСЛО В КАЧЕСТВЕ ИМЕНИ (номер помещения с плана) приходит через normalizeGroup в JS-форме:
   4.10 → «4.1», 4.0 → «4». Это не наш выбор: в JS 4.10 и 4.1 — буквально одно число, хвостовой
   ноль теряется ДО модуля и восстановлению не подлежит. Вызывающему знать: число 4.10 попадёт в
   группу «4.1»; различать «4.1» и «4.10» можно ТОЛЬКО строками — так они и приходят из плана.
   «1» и «01» — РАЗНЫЕ группы (осознанно): ведущий ноль — это написание человека, а не потеря
   представления в JS, угадывать за него мы не вправе. Число 1 при этом даёт ключ «1». */
const groupKeyOf = value => normalizeGroup(value).toLocaleLowerCase("ru-RU");

/* ─────────────────────── чтение полей места ─────────────────────── */

/* ⚠️ ОДНО ПОЛЕ — ОДНА ФУНКЦИЯ ЧТЕНИЯ. Это не стилистика, а корректность: пока номер поста в одном
   месте читался сырым, в другом — разобранным числом, а id поста где-то проверялся на «!= null»
   вместо «задано ли значение», один и тот же проект успевал натворить сразу три вещи:
     • буквенный номер поста стирался из ключа сортировки. Заказчик нумерует посты-выключатели
       с префиксом («В15», «В17» … «В24» — эталон «Расчёт розеток»), Number("В15") = NaN, номер
       уходил из ключа, а место оставалось в выдаче — и порядок задавал ВХОД: инвертор за 42.33 €
       доставался разным ФИЗИЧЕСКИМ постам от вызова к вызову;
     • пустой postId у ДВУХ РАЗНЫХ постов схлопывал их в один пост реестра — ровно тот «ложный
       дубль», который модуль запрещает себе везде;
     • «1» и « 1» были ОДНИМ постом для сортировки и ДВУМЯ для опознания дубля: повтор одного и
       того же места проходил в расчёт, N рос, выключатель превращался в два переключателя.
   Поэтому ниже — по одной функции на поле, и весь модуль (идентичность, порядок, группировка по
   постам, выдача) читает место ТОЛЬКО через них. Разные представления одного поля в разных местах
   и есть источник этого класса ошибок.

   Адресное поле (номер поста, id поста, id товара-клавиши) приводится так:
     • пробелы по краям и внутри нормализуются: « 1» → «1», «пост  7» → «пост 7»;
     • пусто (null/undefined/пустая строка/одни пробелы) → null «значение не задано»;
     • не-адрес (объект, массив, boolean, NaN/Infinity) → null: String({}) = «[object Object]»
       сделал бы два разных поста одним, а Number([]) = 0 — двумя одинаковыми клавишами;
     • ТИП СОХРАНЯЕТСЯ. Номер 12 остаётся числом, «В15» — строкой. Числовые номера идут в порядке
       раньше буквенных, а внутри буквенных коллация с разбором цифр ставит «В2» перед «В10».
       Превращать «01» в 1 мы не вправе (ведущий ноль — написание человека, то же правило, что у
       имени группы), а превращать 12 в «12» значит потерять численный порядок постов.
   Число 1 и строка «1» — ОДИН адрес при опознании дубля (печатаются они одинаково, и пост на
   плане это один и тот же), а в ключе сортировки число стоит раньше строки; порядок при этом
   остаётся определённым при любом входе, а не «как подали». */
function addressFieldOf(value) {
  if (typeof value === "number") return Number.isFinite(value) ? value : null;
  if (typeof value !== "string") return null;
  const text = value.replace(/\s+/g, " ").trim();
  return text === "" ? null : text;
}

const postNumberOf = place => addressFieldOf(place && place.postNumber);
const postIdOf = place => addressFieldOf(place && place.postId);

/* id товара-клавиши: явное поле сильнее вложенного товара (пустое явное поле — это «не задано»,
   и тогда спрашиваем товар, а не считаем клавишу безымянной). */
function keyIdOf(place) {
  const p = place || {};
  const own = addressFieldOf(p.keyId);
  return own !== null ? own : addressFieldOf(p.key && p.key.id);
}

/* Артикул подобранного изделия — тоже идентификатор, и читается он тем же адресным полем: пусто,
   одни пробелы, объект/массив/boolean/NaN → null «артикул не определён» (что с таким изделием
   делает расчёт — см. GAPS.NO_CODE в plan). Отдельная функция здесь по той же причине, что и
   у полей места: одно поле — одно правило чтения на весь модуль. */
const productCodeOf = product => addressFieldOf(product && product.code);

/* Индекс клавиши в посте — ПОЗИЦИЯ, поэтому его каноническая форма всегда число: «0» и 0 — одна
   и та же первая клавиша. Нечисловое значение (объект, boolean, «первая») — это не позиция, и
   место остаётся неопознаваемым (см. identityOf), а не получает выдуманный индекс: Number(true)
   и Number([]) дали бы 1 и 0 и слепили бы разные клавиши в одну.
   ⚠️ СТРОКА ЧИТАЕТСЯ ТОЛЬКО В ДЕСЯТИЧНОЙ ЗАПИСИ (необязательный минус, цифры, необязательная
   дробная часть) — ровно в той, какой человек и JSON записывают позицию. Раньше здесь стоял голый
   Number(), и обещание «не позиция → null» он не выполнял: «0x10» → 16, «0b11» → 3, «1e1» → 10,
   «+3» → 3, «3.» → 3. Выбор в пользу обещания, а не поведения, — не педантизм: keyIndex это
   половина идентичности места (identityOf), и «0x10» молча становилось ТЕМ ЖЕ местом, что и 16, —
   ложный дубль, который выбрасывает настоящую клавишу с плана, занижает N группы (два
   переключателя по 25.79 € превращаются в один выключатель за 20.26 €) и вместе с ним смету.
   Обещанное поведение безопаснее ровно потому, что оно НИЧЕГО НЕ ВЫБРАСЫВАЕТ: место с непонятной
   позицией остаётся в расчёте, просто дубль среди таких мест не ищется (см. identityOf).
   Ведущие нули позиции сохраняем как число («01» → 1): ноль впереди — это написание человека
   только у ИМЕНИ (группа, номер поста), а позиция — число, и «01» с 1 это физически одна и та же
   клавиша. Строку в экспоненциальной записи не принимаем и здесь: если приложение хранит позицию
   числом, оно и придёт числом — верхняя ветка. */
const DECIMAL_INDEX = /^-?\d+(?:\.\d+)?$/;
function keyIndexOf(place) {
  const value = addressFieldOf(place && place.keyIndex);
  if (typeof value === "number") return value;
  if (typeof value !== "string" || !DECIMAL_INDEX.test(value)) return null;
  const n = Number(value);
  return Number.isFinite(n) ? n : null;   /* «999…9» на 400 цифр — Infinity, а не позиция */
}

/* Адрес поста — ОДНО понятие на весь модуль: id, если он задан, иначе номер. По нему опознаётся
   дубль (identityOf) и по нему же места собираются по постам в реестре. Раньше это были два
   разных правила: реестр требовал postId и проверял его на «!= null», поэтому место с номером,
   но без id, в group.posts не попадало вовсе, а два поста с postId «» становились одним. */
function postAddressOf(place) {
  const id = postIdOf(place);
  const number = postNumberOf(place);
  return { id, number, key: id !== null ? "p:" + id : (number !== null ? "n:" + number : null) };
}

/* Серии товара (клавиши). Формат тот же, что productSeries в catalog.js; каталог сюда не тянем —
   модуль обязан оставаться чистым, а нужна нам от серий ровно одна вещь: пусто или нет (пусто →
   честный пробел «серия клавиши неизвестна», а не подбор наугад). Приложение может передать своё
   чтение через deps.seriesOf. */
function defaultSeriesOf(item) {
  const raw = item && (item.series ?? item.compatibility ?? (item.properties && item.properties.series));
  if (Array.isArray(raw)) return raw.map(String).map(s => s.trim()).filter(Boolean);
  return String(raw || "").split(/[,;|]/).map(s => s.trim()).filter(Boolean);
}

/* Серии — это МНОЖЕСТВО, порядок внутри ничего не значит («Eikon Evo, Eikon Exe» и «Eikon Exe,
   Eikon Evo» — одна и та же клавиша). Приводим к одному виду (обрезка, без пустых, без повторов,
   по алфавиту), чтобы один и тот же вопрос к каталогу выглядел одинаково при любом порядке на
   входе — иначе кэш подбора и сам ответ deps зависели бы от того, как приложение сложило список.
   ⚠️ ПОВТОР — ЭТО ТОЧНОЕ СОВПАДЕНИЕ СТРОКИ, а не совпадение «без учёта регистра». Раньше повторы
   отсеивались по приведённому регистру, и написание ВЫЖИВШЕГО элемента задавал ПОРЯДОК ВХОДА:
   [«Eikon Evo», «EIKON EVO»] давало [«Eikon Evo»], а [«EIKON EVO», «Eikon Evo»] — [«EIKON EVO»].
   То есть ровно та зависимость от входа, ради устранения которой функция и написана, только
   внутри одного места (см. большой комментарий про регистр серий ниже).
   Сортировка — тем же cmpText, что и в ключе порядка мест: localeCompare сам по себе НЕ строгий
   полный порядок (две разные строки, равные по коллации, — например NFC и NFD одного имени, —
   он объявляет равными, и их взаимный порядок опять решал бы вход), а cmpText доводит равенство
   по коллации добором по кодам символов. */
function canonicalSeries(list) {
  const seen = new Set();
  const out = [];
  (Array.isArray(list) ? list : []).forEach(raw => {
    const s = String(raw == null ? "" : raw).replace(/\s+/g, " ").trim();
    if (!s || seen.has(s)) return;
    seen.add(s);
    out.push(s);
  });
  return out.sort(cmpText);
}

/* ⚠️ РЕГИСТР СЕРИЙ МОДУЛЬ НЕ ПРИВОДИТ — ни в вопросе к каталогу, ни в ключе кэша, ни в подписи
   серий для сортировки. Раньше приводил (поэлементный toLocaleLowerCase), и это давало
   ЗАВИСИМОСТЬ ЗАПРОСА К КАТАЛОГУ ОТ ПОРЯДКА ВХОДА: ключ кэша регистр приводил, а серии, уходящие
   в deps.findMechanism, — нет (в них сохранялось исходное написание места). Два места с сериями
   [«Eikon Evo»] и [«EIKON EVO»] были для кэша ОДНИМ вопросом, и написание в этом вопросе задавал
   первый ПО ВХОДУ спросивший. Реализация deps, сравнивающая серии как строки, считала один и тот
   же проект по-разному: вход [аккуратное, крикливое] — 40.52 €, вход [крикливое, аккуратное] —
   0 € и оба механизма null.
   Разобранные и отвергнутые способы починки:
     • ПРИВЕСТИ РЕГИСТР И В АРГУМЕНТЕ (одна форма наружу). Порядок чинит, но ломает любую
       реализацию deps, которая ищет по точному написанию: в каталоге серия записана «Eikon Evo»,
       и на вопрос «eikon evo» такая реализация не найдёт НИЧЕГО НИ ОДНОМУ месту — вместо одной
       кривой клавиши пустой становится вся смета. Чинить порядок ценой рабочего расчёта нельзя.
     • СПРАШИВАТЬ КАТАЛОГ В КАНОНИЧЕСКОМ ПОРЯДКЕ. Результат становится воспроизводимым, но одно
       из двух мест по-прежнему получает механизм, подобранный ПО ЧУЖОМУ НАПИСАНИЮ, — тот самый
       запрет «чужую серию не подставляем», от которого модуль защищается везде. Порядок обхода
       мы всё равно сделали каноническим (см. plan), но как отдельную гарантию, а не как починку.
     • ЗАПИСАТЬ В КОНТРАКТ «deps обязан сравнивать серии без учёта регистра». Это обещание за
       чужой код: нарушить его можно молча, а цена нарушения — деньги в смете.
   Принятое правило простое и проверяемое кодом, а не обещанием: КЛЮЧ КЭША РАВЕН АРГУМЕНТУ
   (см. cacheKeyOf в plan). Разные написания — разные вопросы, каждое место получает ответ на
   СВОЁ написание; совпадающие написания, как и прежде, спрашиваются один раз. Знает ли каталог
   про регистр — дело deps, который каталог и видит; модуль за него не решает.
   ПОДПИСЬ СЕРИЙ В КЛЮЧЕ СОРТИРОВКИ (seriesSignature) живёт по ТОМУ ЖЕ правилу: порядок обязан
   различать места ровно теми сериями, какими их различает подбор. Оставь подпись
   регистронезависимой — и два места, отличающиеся только написанием серии, для порядка стали бы
   неразличимы, тайбрейк провалился бы на позицию во входном списке, и раскладка ролей
   (переключатель 25.79 € против инвертора 42.33 €) снова зависела бы от входа. */

/* СЕРИИ МЕСТА — тоже одна функция чтения на весь модуль: и порядок, и подбор механизма обязаны
   различать места ОДНИМИ И ТЕМИ ЖЕ сериями, иначе места, различимые только серией, снова
   раскладываются по ролям в порядке входа. Явное place.series сильнее товара-клавиши.
   ⚠️ Чтение отдано вызывающему (deps.seriesOf) и на неожиданных данных МОЖЕТ БРОСИТЬ. Для модуля,
   вся идея которого «честный пробел вместо неверного числа», сбой ВНЕШНЕЙ ЗАВИСИМОСТИ — это
   пробел, а не падение расчёта всего проекта: ровно так же ведёт себя сбой deps.findMechanism
   (GAPS.LOOKUP_FAILED). Раньше поведение расходилось: в тайбрейке порядка исключение глотал
   try/catch, а тот же вызов в plan ронял весь расчёт целиком. Возвращаем { list, failed }. */
function readPlaceSeries(place, readSeries) {
  const p = place || {};
  if (Array.isArray(p.series) && p.series.length) return { list: canonicalSeries(p.series), failed: false };
  try { return { list: canonicalSeries(readSeries(p.key || p)), failed: false }; }
  catch (e) { return { list: [], failed: true, error: e }; }
}

/* ─────────────────────── канонический порядок мест ─────────────────────── */

/* ⚠️ НАШЕ РЕШЕНИЕ (заказчик правило не оговаривал), и оно ОБЯЗАТЕЛЬНОЕ, а не косметическое.
   Порядок мест внутри группы решает, какие два места получат переключатели, а какие — инверторы
   (см. classicRole). Пока порядок брался «как подал вызывающий», один и тот же проект давал
   РАЗНЫЕ результаты:
     • разную СУММУ сметы — переключатель и инвертор стоят по-разному (20005.0 = 25.79 €,
       20013.0 = 42.33 €), так что перестановка мест между группами меняла итог;
     • разную ВЫЧИСЛИМОСТЬ — роль inverter есть не во всех сериях (Neve Up, см. шапку модуля),
       поэтому при одном порядке проект считался, а при другом упирался в честный пробел.
   Поэтому порядок мест — свойство ПРОЕКТА, а не свойство вызова. Ключ сортировки:
     номер поста → id поста → индекс клавиши в посте → id товара-клавиши → ключ группы →
     печатное имя группы → серии клавиши → позиция во входном списке.
   Первые четыре — «как человек читает план и лист монтажника»: посты по номерам, клавиши слева
   направо внутри поста. Остальные — НЕ УКРАШЕНИЕ, а условие ПОЛНОТЫ порядка, ради которой всё
   и затевалось: пока ключ обрывался на адресе, два места, неразличимых по адресу (обычное дело,
   когда приложение не передало индекс клавиши), но несущих РАЗНУЮ группу или РАЗНУЮ серию,
   раскладывались по ролям в порядке ВХОДА — то есть та же болезнь, только в углу. Раньше здесь
   стояло обоснование «двух одинаковых по первым четырём ключам мест быть не должно — такие
   места ловятся как дубли»; оно НЕВЕРНО (и было неверным): дубль опознаётся только при наличии
   адреса клавиши (см. identityOf), а места без него — законные разные места.
   Ключ ПОЛОН в том смысле, в каком это нужно расчёту: в нём есть КАЖДОЕ поле места, которое
   модуль читает, — адрес поста, адрес и товар клавиши, группа в ключевой и печатной форме,
   серии, — и ровно в той РАЗОБРАННОЙ форме, в какой модуль по ним и решает (см. «чтение полей
   места»: форма у поля одна на весь модуль, сырых написаний расчёт не видит нигде). Сырые
   значения в ключ не входят: два места, различающиеся только тем, что модуль не читает, для
   расчёта неотличимы — любая их перестановка даёт побайтово тот же результат, поэтому
   замыкающая позиция во входном списке ни на что не влияет и стоит там лишь для строгости
   компаратора (строгий полный порядок вместо предпорядка).
   Пустые значения уходят в конец, чтобы места без номера поста не влезали в начало цепи.
   Физически в проходной схеме переключатели стоят по КОНЦАМ цепи, а инверторы между ними, но
   топологию проводки конфигуратор не знает — наш порядок это порядок постов, а не порядок в
   шлейфе. Придёт от заказчика правило лучше — меняется только этот компаратор. */

/* «Значение задано». Поля ключа приходят уже разобранными (адреса — через addressFieldOf, группа
   и серии — через свои функции), но у группы и серий каноническая форма пустоты — это пустая
   СТРОКА, а не null, и в сортировке пустое обязано уходить в конец наравне с null. */
const presentOrNull = value =>
  (value == null || (typeof value === "string" && value.trim() === "") ? null : value);

/* ЕДИНОЕ правило сравнения для ВСЕХ полей ключа — и это не стилистика, а корректность.
   Раньше числа сравнивались численно, а всё остальное — как строки, и на смешанных типах
   порядок становился НЕТРАНЗИТИВНЫМ: 9 < 10 (как числа), 10 < «5» (как строки «10» < «5»),
   «5» < 9 (как строки) — замкнутый цикл. Нетранзитивный компаратор нарушает контракт
   Array#sort: спецификация в этом случае результат не определяет вовсе, он может отличаться
   между движками и даже между запусками на одном движке. Для модуля, где порядок решает, кому
   достанется инвертор за 42.33 €, «не определено спецификацией» — это неопределённая смета.
   Правило (одно на все поля, потому что типы в полях смешиваются — postId бывает и «p1», и 12):
     1) пусто (null/undefined/пустая строка) — в конец;
     2) РАЗРЯД: конечное число всегда раньше не-числа. Сравнение идёт только внутри однородного
        разряда — отсюда и транзитивность, цикл «число ↔ строка» физически не собирается;
     3) внутри чисел — численно; внутри строк — коллацией ru-RU с разбором цифр («p2» < «p10»),
        а при равенстве по коллации — добором по кодам символов, чтобы «5» и «05» не считались
        ОДНИМ значением (иначе на них порядок снова решал бы вход).
   Коллация — эквивалентность (равные по ней строки равны транзитивно), добор по кодам — строгий
   полный порядок, их композиция транзитивна. NaN/Infinity в числовое ветвление не попадают
   (isFiniteNumber), иначе сравнения с NaN, всегда ложные, снова разорвали бы транзитивность. */
const isFiniteNumber = value => typeof value === "number" && Number.isFinite(value);
const COLLATOR = (typeof Intl !== "undefined" && Intl.Collator)
  ? new Intl.Collator("ru-RU", { numeric: true, sensitivity: "variant" }) : null;
function cmpText(sa, sb) {
  const byLocale = COLLATOR ? COLLATOR.compare(sa, sb) : sa.localeCompare(sb, "ru-RU");
  if (byLocale !== 0) return byLocale < 0 ? -1 : 1;
  return sa < sb ? -1 : (sa > sb ? 1 : 0);
}
function cmpValue(a, b) {
  const aEmpty = presentOrNull(a) === null, bEmpty = presentOrNull(b) === null;
  if (aEmpty || bEmpty) return aEmpty && bEmpty ? 0 : (aEmpty ? 1 : -1);   /* пусто — в конец */
  const aNum = isFiniteNumber(a), bNum = isFiniteNumber(b);
  if (aNum !== bNum) return aNum ? -1 : 1;                                 /* числа раньше строк */
  if (aNum) return a < b ? -1 : (a > b ? 1 : 0);
  return cmpText(String(a), String(b));
}
/* Серии места одной строкой — последнее поле ключа сортировки. Читаются той же readPlaceSeries,
   что и в расчёте, чтобы порядок различал места, которые различает подбор: две клавиши разных
   серий в одной группе по одному адресу — это разная цена механизма, и решать, кому достанется
   инвертор, порядок входа не должен. Сбой deps.seriesOf здесь — «серия неизвестна» (пустая
   подпись), как и в расчёте.
   ⚠️ ПОДПИСЬ ОБЯЗАНА БЫТЬ НЕСКЛЕИВАЕМОЙ — по той же причине и тем же способом, что и ключ кэша
   подбора (см. cacheKeyOf в plan). Раньше серии склеивались в строку через «|», и РАЗНЫЕ наборы
   давали ОДНУ подпись: [«Arke|Arke Fit»] (приложение отдало серии одной строкой, не разбив по
   разделителю) и [«Arke», «Arke Fit»] — у обоих «arke|arke fit». Тайбрейк по сериям при этом
   проваливался на замыкающую позицию во входном списке, и раскладка ролей снова зависела от
   ПОРЯДКА ВХОДА: один и тот же проект давал 36.94 € при одном порядке и 48.32 € при другом —
   решалось, кому достанется инвертор 19013.0 за 29.85 €. JSON-кодирование массива разделитель у
   элементов отнять не даёт.
   Пустой набор остаётся ПУСТОЙ СТРОКОЙ, а не «[]»: «серия неизвестна» — это пусто, и в сортировке
   оно обязано уходить в конец наравне с null (см. presentOrNull), а «[]» ушло бы в середину.
   Регистр в подписи НЕ приводится — то же правило, что и у ключа кэша (см. комментарий про
   регистр серий выше): подбор различает написания, значит и порядок обязан их различать. */
function seriesSignature(place, readSeries) {
  const list = readPlaceSeries(place, readSeries).list;
  return list.length ? JSON.stringify(list) : "";
}

/* canonicalOrder(places, seriesOf?) → массив ВХОДНЫХ ИНДЕКСОВ в каноническом порядке.
   seriesOf — то же чтение серий, что и в plan (по умолчанию наше); передаётся, чтобы порядок
   различал места ровно теми же сериями, какими их различает подбор механизма. */
/* ⚠️ ОБХОД ВХОДНОГО СПИСКА — БЕЗ ПРОПУСКА ДЫР, здесь и в plan. list.map/forEach в дыры
   разреженного массива не заходят, а приложение отдаёт именно такой массив после `delete
   places[i]` (удалили клавишу — индексы остальных сохранились). Пока обход шёл через map, место с
   таким индексом не попадало НИ В ПОРЯДОК, НИ В ГРУППУ, НИ В ПРОБЕЛЫ, а выдача возвращалась С
   ДЫРКАМИ: order = [0, 2, <дыра>] и places[1] === undefined — потребитель либо молча терял место
   (его же map/forEach дыру тоже пропустит), либо падал на places[i].code. Array.from читает дыру
   как undefined, дальше место разбирается общим путём и честно становится пробелом «группа не
   назначена»: длина выдачи равна длине входа, дыр в ней нет. */
function canonicalOrder(places, seriesOf) {
  const readSeries = typeof seriesOf === "function" ? seriesOf : defaultSeriesOf;
  const list = Array.isArray(places) ? places : [];
  return Array.from(list, (raw, index) => {
    const p = raw || {};
    return { index, postNumber: postNumberOf(p), postId: postIdOf(p),
      keyIndex: keyIndexOf(p), keyId: keyIdOf(p),
      groupKey: groupKeyOf(p.group), groupLabel: normalizeGroup(p.group),
      series: seriesSignature(p, readSeries) };
  }).sort((a, b) => cmpValue(a.postNumber, b.postNumber) || cmpValue(a.postId, b.postId)
      || cmpValue(a.keyIndex, b.keyIndex) || cmpValue(a.keyId, b.keyId)
      || cmpValue(a.groupKey, b.groupKey) || cmpValue(a.groupLabel, b.groupLabel)
      || cmpValue(a.series, b.series) || (a.index - b.index)
  ).map(row => row.index);
}

/* Опознание места: «та же клавиша того же поста». Нужно, чтобы поймать ДУБЛЬ — одно и то же
   место, поданное дважды. Дубль опасен молча: он увеличивает N группы, а с ним меняются и
   механизм (N=1 выключатель → N=2 два переключателя), и цена.
   ⚠️ КЛАВИША ОПОЗНАЁТСЯ ТОЛЬКО ПОЗИЦИЕЙ В ПОСТЕ (keyIndex), НЕ ТОВАРОМ. Раньше при отсутствии
   keyIndex в ход шёл id ТОВАРА-клавиши — и это ломало самый обычный пост: двухклавишный пост
   собран из двух ОДИНАКОВЫХ клавиш 20021, у обоих мест id товара один и тот же, второе место
   объявлялось дублем и выбрасывалось. Группа теряла место (а то и исчезала целиком), N занижался,
   переключатели превращались в выключатели, смета — в неверную. Товар говорит «что стоит», а не
   «где стоит»; идентичность места — это адрес, и только адрес.
   ⚠️ РЕШЕНИЕ ПРО ОТСУТСТВУЮЩУЮ ПОЗИЦИЮ (наше, явное): keyIndex не передан → места НЕ ОПОЗНАЮТСЯ
   вовсе (identity = null), дубль среди них не ищется, каждое считается за своё. Альтернативу
   «нет позиции → место в пробел» мы отвергли сознательно: это выбросило бы из расчёта настоящую
   клавишу с плана и ЗАНИЗИЛО смету — ровно тот вред, от которого модуль и защищается, причём за
   ошибку формата данных расплачивался бы заказчик. Молчаливым это не остаётся: plan отдаёт у
   такого места keyIndex: null, и вызывающему видно, какие места он подал без позиции.
   Адрес поста и позицию клавиши читают те же postAddressOf/keyIndexOf, что и ключ сортировки с
   реестром: пока опознание читало номер поста сырым, а сортировка — разобранным, «1» и « 1» были
   одним постом для порядка и двумя для дубля, и повтор одного и того же места проходил в расчёт. */
function identityOf(place) {
  const post = postAddressOf(place).key;
  if (post === null) return null;
  const keyIndex = keyIndexOf(place);
  if (keyIndex === null) return null;
  return post + "|i:" + keyIndex;
}

/* Место управления на входе:
     { postId?, postNumber?, keyIndex?, keyId?, key?, series?, group }
   key — товар-клавиша (для серии и для передачи в deps), series — можно задать явно.
   Реестр: по каждой группе — сколько мест и в каких постах. Обход идёт в КАНОНИЧЕСКОМ порядке,
   поэтому и порядок групп, и порядок мест внутри группы, и печатное написание группы не зависят
   от того, в каком порядке места подал вызывающий. Порядок отдаётся наружу (order) — plan берёт
   готовый, чтобы во всём расчёте он был ОДНИМ И ТЕМ ЖЕ, а не пересчитывался второй раз. */
function buildRegistry(places, seriesOf) {
  const list = Array.isArray(places) ? places : [];
  const byKey = new Map();
  const groups = [];
  const unassigned = { placeCount: 0, places: [] };
  const duplicates = [];              /* входные индексы мест-дублей */
  const seen = new Map();             /* identity → входной индекс первого места */
  const postsAt = new Map();          /* «ключ группы + адрес поста» → запись в group.posts */
  const order = canonicalOrder(list, seriesOf);

  order.forEach(index => {
    const place = list[index] || {};
    const identity = identityOf(place);
    if (identity !== null) {
      if (seen.has(identity)) { duplicates.push(index); return; }
      seen.set(identity, index);
    }
    const label = normalizeGroup(place.group);
    const key = groupKeyOf(place.group);
    if (!key) { unassigned.placeCount++; unassigned.places.push(index); return; }
    let group = byKey.get(key);
    if (!group) {
      /* label берём от ПЕРВОГО вхождения В КАНОНИЧЕСКОМ ПОРЯДКЕ: «Кухня» и «кухня» — одна
         группа, а в документах должно печататься написание первого по плану места (не первого
         в списке вызова — иначе название прыгало бы вслед за порядком входа). */
      group = { key, label, placeCount: 0, places: [], posts: [] };
      byKey.set(key, group);
      groups.push(group);
    }
    group.placeCount++;
    group.places.push(index);
    /* Места собираются по постам ПО АДРЕСУ ПОСТА — по тому же понятию, каким опознаётся дубль
       (postAddressOf: id, если задан, иначе номер). Раньше здесь стояло своё правило — «postId
       != null», — и оно давало сразу две беды: пост, у которого приложение передало только номер,
       в group.posts не попадал вовсе, а postId «» у ДВУХ РАЗНЫХ постов проходил проверку и
       схлопывал их в один пост с двумя местами — ложный дубль, запрещённый модулем везде. */
    const address = postAddressOf(place);
    if (address.key !== null) {
      const at = JSON.stringify([key, address.key]);   /* склейка строк дала бы ложные совпадения */
      let post = postsAt.get(at);
      if (!post) {
        post = { id: address.id, number: address.number, placeCount: 0 };
        postsAt.set(at, post);
        group.posts.push(post);
      }
      post.placeCount++;
    }
  });

  /* groups — канонический порядок (по первому месту группы), byKey — быстрый доступ по ключу. */
  return { groups, byKey, unassigned, duplicates, order };
}

/* ─────────────────────── формулы схем ─────────────────────── */

/* Значения вне контракта: index — целое 0…count−1, count — целое ≥1. Всё остальное (N=0,
   отрицательные, дробные, NaN, строки) — не «крайний случай расчёта», а ошибка вызывающего:
   отдаём null «роли нет», а не правдоподобную роль. Правило проекта — честный пробел лучше
   правдоподобно неверного числа; молчаливый SWITCH при count=0 как раз и был бы таким числом. */
function isValidPlaceIndex(index, count) {
  return Number.isInteger(index) && Number.isInteger(count)
    && count >= 1 && index >= 0 && index < count;
}

/* ЕДИНСТВЕННЫЙ источник истины классической схемы (§2.2 ТЗ):
     N = 1  → выключатель;
     N = 2  → ДВА переключателя (по одному на каждом месте);
     N ≥ 3  → ДВА переключателя + (N − 2) инвертора.
   Обе последние строки — это одно и то же правило «первые два места переключатели, остальные
   инверторы», поэтому отдельной ветки на N=2 нет: вторая копия правила рано или поздно разошлась
   бы с первой. Общий итог по группе НЕ считается своей формулой нигде — он получается подсчётом
   ролей в распределении по местам.
   КАКИЕ ИМЕННО два места получают переключатели — «первые два» в каноническом порядке мест
   (см. canonicalOrder): выбор от порядка входа не зависит, поэтому и раскладка, и сумма сметы, и
   сама вычислимость проекта воспроизводятся при каждом пересчёте. */
function classicRole(index, count) {
  if (!isValidPlaceIndex(index, count)) return null;
  if (count <= 1) return ROLES.SWITCH;
  return index < 2 ? ROLES.CHANGEOVER : ROLES.INVERTER;
}

/* Схема с реле: за каждым местом — кнопка ХХ008.0, число мест на роль не влияет (но само место
   обязано быть валидным — иначе роли нет, как и в классической). */
const relayRole = (index, count) => (isValidPlaceIndex(index, count) ? ROLES.BUTTON : null);

/* Потребность в импульсных реле на группу с N кнопками. Про ceil(N/4) — см. MAX_BUTTONS_PER_RELAY:
   вывод из презентации, не прямое слово заказчика. N вне контракта (пусто, отрицательное, NaN,
   не число) → 0 реле: отрицательное количество в спецификации хуже нуля. */
function relayCount(buttonCount) {
  const n = Number(buttonCount);
  if (!Number.isFinite(n) || n <= 0) return 0;
  return Math.ceil(n / MAX_BUTTONS_PER_RELAY);
}

/* Роль места по схеме — одна точка входа, чтобы schemes не расползлись по модулю. */
function roleFor(scheme, index, count) {
  if (scheme === "classic") return classicRole(index, count);
  if (scheme === "relay") return relayRole(index, count);
  return null;   /* bell и всё нераспознанное — механизм не подбираем */
}

