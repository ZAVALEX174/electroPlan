/* Комната — чистая логика уровня помещения (PLAN 2.1). Пока здесь одно: разрешение схемы
   электрики комнаты. Модуль без state, DOM и каталога — все зависимости приходят аргументами,
   как в posts.js/estimate.js, чтобы функции забирали автотесты (PLAN 7.1).

   --- СХЕМА ЭЛЕКТРИКИ КОМНАТЫ ---------------------------------------------------------
   Схема электрики была свойством ПРОЕКТА (EP_DATA.settings.lightingScheme). Теперь у комнаты
   может быть СВОЯ схема (room.lightingScheme), а настройка проекта остаётся значением по
   умолчанию — ровно как тип стены у поста (EPPosts.postWallType).

   ⚠️ ОТСУТСТВИЕ ПОЛЯ — ЭТО НЕ «неизвестно», А «КАК В ПРОЕКТЕ». Все комнаты, сохранённые до этой
   правки, поля не имеют и обязаны продолжать читать схему проекта: иначе старый проект при
   первом открытии посчитал бы часть комнат по «пустой» схеме. Поэтому фолбэк — именно схема
   проекта. Пустая строка/мусор/не-строка трактуются так же, как отсутствие: комната следует
   за проектом.

   ⚠️ НЕИЗВЕСТНЫЙ id СХЕМЫ — ТОЖЕ ФОЛБЭК НА ПРОЕКТ. Если в поле осталась схема, которой больше
   нет в списке (переименовали/убрали), это «мёртвое» значение, а не действующая настройка —
   отдаём схему проекта, а не рисуем несуществующую. Список допустимых id приходит аргументом
   schemes (массив id или объектов {id}), чтобы модуль не тянул EPLightingGroups и остался
   чистым. Список не передан — проверку id не делаем, валидной считается любая непустая строка. */
(() => {
"use strict";

function roomLightingScheme(room, projectScheme, schemes) {
  const own = room && room.lightingScheme;
  if (typeof own === "string" && own) {
    if (!schemes) return own;                                   /* список не задан — не проверяем id */
    const ids = schemes.map(s => (s && typeof s === "object" ? s.id : s));
    if (ids.indexOf(own) !== -1) return own;                    /* своя валидная схема */
  }
  return projectScheme;                                          /* нет поля / мусор / мёртвый id → проект */
}

/* --- КОЛЛЕКЦИЯ (СЕРИЯ) ОТДЕЛКИ КОМНАТЫ (E13) --------------------------------------------
   За помещением закрепляется коллекция накладок; конструктор поста в этой комнате предлагает
   только её (встреча 24.08 §4.1–4.2). Разрешение значения — здесь, рядом с roomLightingScheme,
   но правило ОТЛИЧАЕТСЯ в одном: у коллекции НЕТ значения-умолчания на уровне проекта.

   ⚠️ ОТСУТСТВИЕ ПОЛЯ / МУСОР → null («коллекция не задана»), а НЕ значение проекта. null означает
   «фильтра нет, предлагаем весь каталог» — ровно то, что нужно посту вне комнат и комнате без
   выбранной коллекции. Старый проект без поля room.collection открывается именно так, ничего не
   ломая: у него коллекция не задана, каталог не сужается.

   ⚠️ НЕИЗВЕСТНАЯ КОЛЛЕКЦИЯ — ТОЖЕ null. Если в поле осталась коллекция, которой больше нет в
   каталоге (переименовали серию, перезалили прайс), это «мёртвое» значение: фильтровать каталог
   по несуществующей серии нельзя — вернём null (весь каталог), а не пустой список. Список
   допустимых названий приходит аргументом collections (из EPCatalog.productCollections), чтобы
   модуль остался чистым. Список не передан — проверку названия пропускаем, валидной считаем
   любую непустую строку (симметрично roomLightingScheme). */
function roomCollection(room, collections) {
  const own = room && room.collection;
  if (typeof own !== "string" || !own) return null;              /* нет поля / пусто / не-строка → не задана */
  if (!collections) return own;                                  /* список не задан — не проверяем название */
  return collections.indexOf(own) !== -1 ? own : null;           /* мёртвое (нет в каталоге) название → не задана */
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2),
   Node — module.exports для автотестов (PLAN 7.1). */
const api = { roomLightingScheme, roomCollection };
if (typeof window !== "undefined") window.EPRoom = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
