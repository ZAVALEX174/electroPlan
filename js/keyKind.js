/* Вид клавиши: простая или с символом/диффузором (К14 ч.2).

   ЗАЧЕМ. Заказчик 15.10 (0:20:07): «было бы классно, чтобы у меня в конфигураторе осталось
   вот всего там два типа кнопки. Такая широкая и такая узкая». Решение владельца 02.11: в
   разделе каталога «Клавиша» по умолчанию показываем только ПРОСТЫЕ клавиши (узкую/широкую/
   3-модульную на каждый цвет), а клавиши с символами («звонок», «лампа», «ключ», «PRESS»,
   ON/OFF, стрелки, сценарии и т. п.) и с диффузором уводим в отдельный свёрнутый раздел
   «Клавиши с символами» сразу после «Клавиша». Делит их ровно эта функция — в ОДНОМ месте
   (§7.1), чтобы у правила не было краёв: и фильтр по месту, и поиск, и будущие потребители
   сверяются по одному признаку.

   ПРАВИЛО — ПО НАЗВАНИЮ, НЕ ПО СУФФИКСУ АРТИКУЛА. Суффикс ненадёжен: в Linea «.C» — это ЦВЕТ
   «конопляная» (31000.C), а символ «звонок» кодируется «.CB/.CC/.CG»; в Arke/Eikon «.C» —
   наоборот «звонок». Название же у VIMAR единообразно называет символ словом: «с символом
   "звонок"», сокращённо «с симв "лампа"», «с диффузором», «сценария "Дом"». Простые клавиши
   символа в названии не упоминают («Клавиша на 1 модуль, белая», «Две плоские клавиши без
   символов…», «с индикатором "кольцо"» — индикатор-кольцо это не печатный символ).
   Ловушка «без символов» (22751.0.*) — это ПРОСТАЯ клавиша, хотя слово «символ» в названии
   есть: отсекаем её явной проверкой «без символ…».

   Проверено на реальном каталоге (functionalGroup «Клавиша», 245 позиций): простых 64,
   с символами/диффузором 181. По сериям простых/с символами: Arke 8/30, Eikon Evo 9/24,
   Plana 8/8, Eikon Tondo 9/0, Eikon Flat 12/53, Linea 18/66 (Neve Up 09021/09022/09026 и
   Bluetooth-клавиши лежат в других группах — «Клавиши»/«Отели»/«Клавиши BLUETOOTH» — и этого
   деления не касаются).

   Модуль ЧИСТЫЙ: ни DOM, ни state, ни каталога — на вход товар, на выход признак. */
(() => {
"use strict";

/* Подпись раздела для клавиш с символами. Нормализацию имени (регистр/пробелы/ё→е) НЕ дублируем:
   её единственный держатель — EPCatalogSections.keyOf (§7.1), сопоставление раздела делает
   потребитель через него. */
const SYMBOL_GROUP_LABEL = "Клавиши с символами";
/* Имя исходного раздела, который делим. Держим строкой здесь, чтобы и подпись, и ключ порядка
   в DEFAULT_ORDER (catalogSections.js) сверялись с одним написанием. */
const KEY_GROUP_LABEL = "Клавиша";

/* Простая ли это клавиша (без печатного символа и без диффузора). Вызывается ТОЛЬКО для клавиш
   раздела «Клавиша» — признак берёт по названию (см. шапку). Для не-клавиши вернёт true, но
   потребитель её сюда не приводит. */
function isSimpleKey(item) {
  const name = String((item && item.name) || "").toLowerCase();
  if (/диффузор/.test(name)) return false;                 // рассеиватель — не простая клавиша
  if (/сценари/.test(name)) return false;                  // клавиши сценариев («Дом», рольставни) — с печатью
  if (/симв/.test(name) && !/без\s+симв/.test(name)) return false; // «символ»/«симв», кроме «без символов»
  return true;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — для автотестов. */
const api = { isSimpleKey, SYMBOL_GROUP_LABEL, KEY_GROUP_LABEL };
if (typeof window !== "undefined") window.EPKeyKind = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
