/* Ориентация накладки: горизонтальная ↔ вертикальная ПАРА одной отделки (Б8) — ЧИСТАЯ доменная
   логика над товаром-накладкой. Модуль без state, DOM и каталога: список накладок приходит
   аргументом, как buttonFrame.js/posts.js (PLAN 7.1). Здесь ОДНО место правила «какая накладка
   является вертикальным/горизонтальным двойником данной»: его спрашивают и отметка в окне поста
   (связь в обе стороны), и — в ЧАСТИ 2 — перевыбор пары при смене модульности/комнаты/копировании.
   Второй копии правила нет, поэтому у правки нет краёв.

   --- ЧТО ТАКОЕ ПАРА -----------------------------------------------------------------------------
   У накладок LINEA есть двойники «горизонтально ↔ вертикально» одной и той же отделки: 30643.*
   «Накладка на 4 модуля (2+2) … <отделка>» ↔ 30645.* «… (2+2) ВЕРТИКАЛЬНО … <отделка>», 30644.*
   (6М 2+2+2) ↔ 30646.*. У пары совпадают серия, число прорезей (slotCount), отделка (суффикс
   артикула после базы и текст отделки в имени), цена и раскладка — различается только расположение
   прорезей: горизонтальное против вертикального. Клиент-заказчик (15.10) попросил вертикальное
   расположение отдельным блоком: «итальянцы не подразумевают вертикальное расположение, но здесь
   такой клиент».

   --- ПОЧЕМУ ПО ПРИЗНАКАМ, А НЕ ХАРДКОДОМ АРТИКУЛОВ ----------------------------------------------
   Пару определяем устойчиво по данным (серия + slotCount + суффикс отделки + слово «вертикально» в
   имени), а НЕ списком «30643↔30645», чтобы перезалив прайса с новыми отделками/сериями не требовал
   правки кода. Признак вертикальной — слово « вертикально» в названии (в каталоге им помечены ровно
   24 накладки, и `name.replace(' вертикально','')` даёт имя горизонтального двойника — проверено
   24/24). Имя БЕЗ этого слова — ключ «та же накладка»: он включает текст отделки, поэтому двойника
   другой отделки (…белая vs …конопляная) не захватывает. Дополнительные признаки (slotCount, суффикс
   артикула, серия) — страховка от ложного совпадения: если под признаки подходит не ровно один
   кандидат, пару НЕ отдаём (null) — молча выдуманного двойника лучше не подставлять (§7.1).

   В 4М-пуле LINEA рядом лежат 30654.* «Накладка на 4 модуля …» и 30944.* (IP55) — у них двойника
   нет: имя у них другое, слова «вертикально» нет, pairOf вернёт null, и отметка на них не влияет. */
(() => {
"use strict";

/* Признак вертикальной накладки — слово « вертикально» в названии (с ведущим пробелом, чтобы не
   цеплять словообразования; ровно так помечены 24 накладки каталога). */
function isVertical(frame) {
  return !!frame && / вертикально/.test(String(frame.name || ""));
}

/* Имя БЕЗ признака вертикальности — ключ «та же накладка» (включает текст отделки). У горизонтальной
   это её имя, у вертикальной — имя её горизонтального двойника (name.replace, 24/24 совпадений). */
function baseName(frame) {
  return String((frame && frame.name) || "").replace(" вертикально", "");
}

/* Суффикс отделки — часть артикула после базы (первой точки): «30645.01» → «01», «30646.70.01» →
   «70.01». У двойников совпадает (та же отделка). */
function facingSuffix(code) {
  const c = String(code || "");
  const i = c.indexOf(".");
  return i < 0 ? "" : c.slice(i + 1);
}

/* Число прорезей — то же поле, что читают frameLayout/frameSlotCount (slotCount каталога). */
function slotCountOf(frame) {
  return Number(frame && (frame.slotCount ?? frame.slots ?? frame.placeCount)) || 0;
}

/* Ключ серии накладки из возможных полей прайса (массив или строка), нормализованный — для сверки,
   что двойник ИЗ ТОЙ ЖЕ серии. Тот же набор полей, что у EPCatalog.productSeries. */
function seriesKey(frame) {
  const raw = frame && (frame.series ?? frame.compatibility);
  const arr = Array.isArray(raw) ? raw : String(raw || "").split(/[,;|]/);
  return arr.map(s => String(s || "").trim().toLowerCase()).filter(Boolean).sort().join("|");
}

/* Двойник ПРОТИВОПОЛОЖНОЙ ориентации той же накладки (серия + slotCount + суффикс отделки + имя без
   слова «вертикально»), или null. Ровно один кандидат → он; ноль или несколько (неоднозначность) →
   null: выдуманного двойника не подставляем (§7.1). kind проверяем, чтобы случайное совпадение имени
   механизма не выдало механизм за накладку. */
function pairOf(frame, frames) {
  if (!frame || (frame.kind && frame.kind !== "frame")) return null;
  const vert = isVertical(frame);
  const key = baseName(frame), suf = facingSuffix(frame.code), sc = slotCountOf(frame), sk = seriesKey(frame);
  const hits = (Array.isArray(frames) ? frames : []).filter(f =>
    f && f !== frame && (!f.kind || f.kind === "frame") &&
    isVertical(f) !== vert &&
    baseName(f) === key && facingSuffix(f.code) === suf &&
    slotCountOf(f) === sc && seriesKey(f) === sk);
  return hits.length === 1 ? hits[0] : null;
}

/* Есть ли у накладки двойник (от этого зависит, связана ли отметка с полем «Накладка»). */
function hasPair(frame, frames) {
  return !!pairOf(frame, frames);
}

/* Вертикальный член пары: сама накладка, если она уже вертикальная; иначе её двойник (или null,
   если вертикального двойника нет). */
function verticalOf(frame, frames) {
  if (!frame) return null;
  return isVertical(frame) ? frame : pairOf(frame, frames);
}

/* Горизонтальный член пары — симметрично verticalOf. */
function horizontalOf(frame, frames) {
  if (!frame) return null;
  return isVertical(frame) ? pairOf(frame, frames) : frame;
}

/* Накладка нужной ориентации для frame. Двойника нет → сам frame (ориентация не меняется): отметка
   у накладки без пары просто хранится, накладку не трогает. Так окно поста одной функцией решает,
   на какой артикул переписать frameId при включении/снятии отметки. */
function oriented(frame, frames, vertical) {
  const target = vertical ? verticalOf(frame, frames) : horizontalOf(frame, frames);
  return target || frame || null;
}

/* «Вертикален ли ПОСТ» — ОДНО место правила вопроса, который потребители раньше решали каждый по
   своему признаку. Пост вертикален, если стоит отметка (flag) ИЛИ его собственная накладка уже
   вертикальная. Второй признак обязателен для СТАРЫХ постов/шаблонов, собранных вертикальной накладкой
   РУКАМИ до Б8: поля-флага у них нет, но вертикальность видна по самой накладке. frames не нужен —
   ориентацию накладки читаем по имени (isVertical). */
function isVerticalPost(frame, flag) {
  return flag === true || isVertical(frame);
}

/* «Та же накладка на ДРУГОЕ число модулей» — для смены модульности у поста с РУЧНОЙ вертикальной
   накладкой. Ищем изделие ТОЙ ЖЕ серии, с ТЕМ ЖЕ суффиксом отделки и ТОЙ ЖЕ ориентацией, но с нужным
   числом прорезей (count). Поиск по ВСЕМУ переданному списку, НЕ по пулу комнаты: накладку могли выбрать
   руками «чужую» комнате (LINEA-накладка в комнате Arke), и держать надо серию НАКЛАДКИ, а не комнаты —
   иначе 4→6 подставит 6М-накладку чужой серии и перепишет состав и цену. Ровно один кандидат → он; ноль
   или несколько (неоднозначность) → null: накладку НЕ трогаем, ручной выбор главнее выдуманной подмены
   (§7.1). baseName не сверяем — у 4М и 6М двойников имена различаются числом модулей; ключ пары здесь —
   серия + суффикс отделки + ориентация. */
function sameFacingAtCount(frame, count, frames) {
  if (!frame || (frame.kind && frame.kind !== "frame")) return null;
  const vert = isVertical(frame), suf = facingSuffix(frame.code), sk = seriesKey(frame), want = Number(count) || 0;
  const hits = (Array.isArray(frames) ? frames : []).filter(f =>
    f && f !== frame && (!f.kind || f.kind === "frame") &&
    isVertical(f) === vert && facingSuffix(f.code) === suf && seriesKey(f) === sk &&
    slotCountOf(f) === want);
  return hits.length === 1 ? hits[0] : null;
}

/* Состояние отметки «Расположить вертикально» для выбранной накладки. У накладки С ПАРОЙ отметка
   СТРОГО отражает ориентацию самой накладки (связь в обе стороны: выбрал вертикальную руками —
   загорелась, горизонтальную — погасла). У накладки БЕЗ пары (и когда накладка не разрешилась)
   отметка — свободный флаг: сохранённое у поста значение, на состав не влияющее. */
function checkboxChecked(frame, flag, frames) {
  return hasPair(frame, frames) ? isVertical(frame) : !!flag;
}

/* Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — module.exports для тестов. */
const api = { isVertical, pairOf, hasPair, verticalOf, horizontalOf, oriented, checkboxChecked, isVerticalPost, sameFacingAtCount };
if (typeof window !== "undefined") window.EPFrameOrientation = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
