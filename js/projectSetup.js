/* Окно «Данные проекта и КП» (#kpSetupModal). Владелец 20.10: «все данные для кп и т.д. нужно давать
   вносить на самом первом этапе создания проекта, а потом просто скрывать, но оставлять какую-то кнопку
   для возможного редактирования». Поэтому на чистом старте окно открывается САМО, а кнопка «Данные КП»
   в шапке открывает его для правки.

   УСТРОЙСТВО — как у EPProjectFile/EPDocs: ЧИСТАЯ функция решения «открывать ли окно само» (покрыта
   тестом + мутацией) живёт в api; attach(ctx) — тонкая связка: провязывает кнопку шапки, «Готово»,
   крестик и клик мимо, возвращает open/close/maybeOpenOnLoad, которые зовёт app.js. Логики в attach нет.

   Поля окна (объект/адрес, заказчик, мои реквизиты, картинки бланка, условия сметы, состав КП) — ТЕ ЖЕ
   элементы, что раньше стояли на рабочем экране: их заполняют/читают/печатают прежние функции app.js по
   id, у значения один источник. Этот модуль их не трогает — только показывает и прячет окно.

   РЕШЕНИЕ 1 (что открывать само): окно открывается само ТОЛЬКО когда проекта ещё нет — новый проект
   (после «Новый проект» перезагружает страницу с чистым ProjectStore) и первый запуск. Восстановленный
   и открытый из файла проект окно сам НЕ показывает: их данные уже введены. Отсюда shouldOpenOnLoad —
   чистое отрицание «есть ли проект»; зовёт его app.js из init() только на обычной загрузке, а путь
   «Открыть из файла» (EPProjectFile) init не проходит, поэтому своё окно сам не поднимает.

   РЕШЕНИЕ 2 (что подставлять): «мои реквизиты можно повторить, данные заказчика — вносятся каждый раз».
   Это уже обеспечено разделением хранилищ, а не кодом окна: мои реквизиты и бланк (ep_prefs) переживают
   «Новый проект» (ProjectStore.clear их не трогает) и подставляются прежним fill, а объект/адрес и
   заказчик лежат в снимке проекта — на чистом старте пусты. Окно их лишь показывает.

   Двойной экспорт: браузеру — namespace (сборщика нет, PLAN 2.2), Node — module.exports для тестов. */
(() => {
"use strict";

/* Открывать ли окно само на загрузке. Проекта нет (новый/первый запуск) → да; проект есть
   (восстановлен) → нет. hasProject — восстановлен ли проект (app.js передаёт !!restored). */
function shouldOpenOnLoad(hasProject) { return !hasProject; }

function attach(ctx) {
  const { $ } = ctx;
  const modal = $("kpSetupModal");

  function open() { if (modal) modal.classList.add("open"); }
  function close() { if (modal) modal.classList.remove("open"); }
  function isOpen() { return !!modal && modal.classList.contains("open"); }
  /* Зовётся из init() на обычной загрузке: открывает окно только на чистом старте (решение 1). */
  function maybeOpenOnLoad(restored) { if (api.shouldOpenOnLoad(!!restored)) open(); }

  if (modal) {
    $("kpDataBtn").onclick = open;                 // «Данные КП» в шапке — открыть для правки
    $("kpSetupDone").onclick = close;              // «Готово» — скрыть окно, значения уже записаны по ходу ввода
    $("kpSetupClose").onclick = close;             // крестик
    modal.onclick = e => { if (e.target === modal) close(); };   // клик мимо — закрыть, как у прочих окон
  }

  return { open, close, isOpen, maybeOpenOnLoad };
}

const api = { shouldOpenOnLoad, attach };
if (typeof window !== "undefined") window.EPProjectSetup = api;
if (typeof module !== "undefined" && module.exports) module.exports = api;
})();
