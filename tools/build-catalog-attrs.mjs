/*
 * Воспроизводимый генератор признаков автосостава поста → js/catalog-vimar-attrs.js.
 *
 * Для автосостава поста приложению нужны признаки, которых нет в самом каталоге
 * (js/catalog-vimar.js): монтажный СТАНДАРТ накладки, СТАНДАРТ+модульность СУППОРТА,
 * ТИП СТЕНЫ + форма + совместимые стандарты КОРОБКИ и МОНТАЖНОЕ ПРАВИЛО позиции
 * («Принцип обработки» + «Модульность для коробки»). Раньше их собирали эвристикой из
 * прайса (price-parsed.csv) и внешнего каталога совместимости; теперь всё это есть в
 * номенклатуре заказчика в явном виде — читаем и классифицируем через
 * tools/lib/nomenclature.mjs (тот же источник, что и состав каталога).
 *
 * Формат вывода (window.EP_VIMAR_ATTRS) расширяется только необязательными ключами —
 * js/data.js подмешивает эти поля к товарам при загрузке (frames→standard/postCount
 * [+layoutRows, principle, boxModularity], supports→standard/modules/pitchMm [+principle,
 * boxModularity], boxes→wallType/shape/modules/standards [+principle, boxModularity]).
 * У позиции без монтажного правила запись прежняя, поэтому старые автотесты формата
 * остаются в силе. Плюс раздел mounting — монтажное правило видов, у которых своего
 * раздела признаков нет (механизмы, аксессуары): у них заполнен только «Принцип
 * обработки», а стандарт сборки и модульность поста им ни к чему.
 *
 * Флаги: --nom файл номенклатуры (.xls), --out выходной файл.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { readNomenclature, applyKindOverrides, buildAttrs, DEFAULT_NOMENCLATURE } from "./lib/nomenclature.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, "..");

const { values: args } = parseArgs({ options: { nom: { type: "string" }, out: { type: "string" }, overrides: { type: "string" } } });
const NOM = args.nom ? path.resolve(args.nom) : DEFAULT_NOMENCLATURE;
const OUT = args.out ? path.resolve(args.out) : path.join(projectRoot, "js/catalog-vimar-attrs.js");
const OVERRIDES = args.overrides ? path.resolve(args.overrides) : path.join(here, "data/kind-overrides.json");

async function main() {
  const { records } = readNomenclature(NOM);
  // Тот же оверрайд kind, что и в build-catalog.mjs: attrs автосостава должны совпадать
  // с каталогом. 14901–14904 → socket_box попадут сюда в boxes с их признаками (тип
  // стены/форма/модульность), accessory-позиции автосостава поста не имеют → не в attrs.
  let overridesDoc = { overrides: {} };
  try { overridesDoc = JSON.parse((await fs.readFile(OVERRIDES, "utf8")).replace(/^﻿/, "")); } catch { /* нет файла — ноль правок */ }
  applyKindOverrides(records, overridesDoc.overrides || {});
  const { standards, supports, boxes, wallTypes, mounting } = buildAttrs(records);

  const tally = (obj, pick) => {
    const t = {};
    for (const c in obj) { const k = pick(obj[c]); t[k] = (t[k] || 0) + 1; }
    return t;
  };

  const banner =
    `/* Generated by tools/build-catalog-attrs.mjs из «${path.basename(NOM)}» — НЕ ПРАВИТЬ РУКАМИ.\n` +
    `   Признаки автосостава поста: стандарт накладки/суппорта, тип стены + форма +\n` +
    `   совместимые стандарты коробки, монтажное правило позиции (principle +\n` +
    `   boxModularity; у механизмов — раздел mounting). Подмешиваются к товарам в js/data.js. */\n`;
  const body = {
    generatedAt: new Date().toISOString().slice(0, 10),
    source: {
      standards: path.basename(NOM),
      supports: path.basename(NOM),
      wallTypes: path.basename(NOM),
      boxes: path.basename(NOM),
      mounting: path.basename(NOM),
    },
    standards,
    supports,
    wallTypes,
    boxes,
    mounting,
  };
  await fs.writeFile(OUT, banner + `window.EP_VIMAR_ATTRS = ${JSON.stringify(body, null, 2)};\n`, "utf8");

  console.log("Готово:", path.relative(projectRoot, OUT));
  console.log(`  накладок со стандартом: ${Object.keys(standards).length} — ${JSON.stringify(tally(standards, (a) => a.standard))}`);
  console.log(`  суппортов:              ${Object.keys(supports).length} — ${JSON.stringify(tally(supports, (a) => a.standard))}`);
  console.log(`  коробок:                ${Object.keys(boxes).length} (с типом стены ${Object.keys(wallTypes).length})`);
  // Монтажное правило считаем по ВСЕМ разделам сразу — это сквозной признак, и по его
  // сумме сверяется полнота проброса (в номенклатуре «Принцип обработки» заполнен у 449).
  const withRule = (obj, key) => Object.values(obj).filter((a) => a[key] != null).length;
  const rules = [standards, supports, boxes, mounting];
  console.log(`  монтажное правило:      principle у ${rules.reduce((s, o) => s + withRule(o, "principle"), 0)}, ` +
    `boxModularity у ${rules.reduce((s, o) => s + withRule(o, "boxModularity"), 0)} ` +
    `(из них у механизмов/прочих: ${Object.keys(mounting).length})`);
}

main().catch((err) => {
  console.error("Ошибка генерации атрибутов:", err);
  process.exitCode = 1;
});
