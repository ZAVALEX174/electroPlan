/*
 * Выдача стабильных id товарам каталога — чистая функция, детерминированная и
 * бесколлизионная (задача К2, починка дефекта пересечения id 18.10).
 *
 * Прежняя схема `id = 200000 + номер строки в файле номенклатуры` ломалась при смене
 * файла: номера строк «поехали», и свежевыданный id совпал с id, который прежняя сборка
 * уже отдала ДРУГОМУ артикулу (пример: id 201686 достался и «21653.01», и «20022.P.N»).
 * На этот id ссылаются сохранённые проекты, поэтому коллизия отдаёт посту чужую цену и
 * состав.
 *
 * Новая схема не зависит от строк вовсе: артикулы, которых ещё нет в карте, получают id
 * ВЫШЕ максимального из уже выданных (max+1, max+2, …) в отсортированном по коду порядке.
 * Так новый id физически не может совпасть с занятым, а порядок (сортировка) делает выдачу
 * воспроизводимой: тот же вход → тот же результат. Повторная сборка новых кодов не находит
 * (они уже в карте) и ничего не меняет.
 */

/* Присваивает id всем кодам из `codes`, опираясь на уже выданные (`seedIds`: code→id).
   Возвращает { idMap, assigned }: idMap — полная карта (сид + новые), assigned — список
   { code, id } новых, в порядке выдачи (по коду). seedIds не мутируется. */
export function assignStableIds(seedIds, codes) {
  const idMap = { ...(seedIds || {}) };
  // Максимум среди ВСЕХ уже выданных id (а не только встреченных в этом файле) — новый id
  // гарантированно больше любого занятого, включая id снятых с производства артикулов,
  // что остаются в карте ради сохранённых проектов.
  let maxId = 0;
  for (const v of Object.values(idMap)) {
    const n = Number(v);
    if (Number.isFinite(n) && n > maxId) maxId = n;
  }
  // Новые коды — отсортированы по коду (детерминированный порядок выдачи, не зависит от
  // порядка строк в файле). Дубли входа схлопываем — один код получает один id.
  const newCodes = [...new Set(codes)].filter((c) => idMap[c] == null)
    .sort((a, b) => String(a).localeCompare(String(b), "en"));
  const assigned = [];
  let next = maxId + 1;
  for (const code of newCodes) {
    idMap[code] = next;
    assigned.push({ code, id: next });
    next++;
  }
  return { idMap, assigned };
}

/* Проверка уникальности id в готовом каталоге — страховка от повторения дефекта. Бросает
   с перечнем столкнувшихся id и их артикулов, если два товара делят один id. Вызывать
   ПЕРЕД записью результата: лучше упасть сборкой, чем отдать посту чужую цену. */
export function assertUniqueIds(products) {
  const byId = new Map();
  for (const p of products) {
    if (!byId.has(p.id)) byId.set(p.id, []);
    byId.get(p.id).push(p.code);
  }
  const collisions = [...byId.entries()].filter(([, codes]) => codes.length > 1);
  if (collisions.length) {
    const detail = collisions
      .map(([id, codes]) => `id ${id} ← ${codes.join(", ")}`)
      .join("; ");
    throw new Error(
      `Коллизия id в каталоге: ${collisions.length} id заняты несколькими артикулами (${detail}). ` +
      `Сборка остановлена — иначе посты на этих артикулах получат чужую цену и состав.`
    );
  }
}
